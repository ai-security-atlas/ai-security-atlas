"""Maintainer tool: regenerate explainer/data.js from a reference container run. Run from labs/
after Steps 1-5 and D1-D3:

    docker compose run --rm workbench python attack-model-imitation/scripts/export_explainer_data.py

Everything in data.js comes from that run: the step JSON files in work/, the query digit and its
four answers, 24 pool digits with the victim's labels, and the first 16 hidden units' input
weights of the victim and of the probability copy (scaled to -100..100). A student's own work/
folder never changes the shipped data.js.
"""
import json

import numpy as np

import labkit

labkit.banner()

import theft  # noqa: E402

W = labkit.work()
need = ["victim.json", "s02.json", "steal.json", "compare.json", "noise.json", "d1.json", "d2.json", "d3.json"]
missing = [f for f in need if not (W / f).exists()]
if missing:
    raise SystemExit(f"[!!] missing work/{missing[0]}: run Steps 1-5 and D1-D3 first")
J = {f[:-5]: json.loads((W / f).read_text()) for f in need}

X, y, S = theft.data()
victim, copy = theft.load("victim.safetensors"), theft.load("copy_probs.safetensors")
pool = X[S["pool"][:24]]


def w16(m):
    w = m[0].weight.detach().numpy()[:16]
    return np.round(100 * w / np.abs(w).max()).astype(int).flatten().tolist()


s02 = J["s02"]
data = {
    "canary": theft.CANARY,
    "victim": J["victim"],
    "query": {"x": [round(v * 16) for v in s02["x"]], "true": s02["true"], "answers": s02["answers"]},
    "pool": [[round(v * 16) for v in row] for row in pool.tolist()],
    "pool_labels": theft.predict(victim, pool).tolist(),
    "steal": J["steal"],
    "compare": J["compare"],
    "weights": {"victim": w16(victim), "copy": w16(copy)},
    "noise": J["noise"],
    "d1": J["d1"],
    "d2": {k: J["d2"][k] for k in ("budget", "sybils", "fid_one", "fid_sybil")},
    "d2_monitor": J["d2"]["monitor"],
    "d3": J["d3"],
}
js = ("/* Shipped reference run for the attack-model-imitation explainer. Generated by\n"
      " * scripts/export_explainer_data.py from a reference container run; do not edit by hand. */\n"
      "window.LAB_DATA = " + json.dumps(data, separators=(",", ":")) + ";\n")
out = labkit.lab() / "explainer" / "data.js"
out.write_text(js)
print(f"wrote {out} ({len(js) / 1024:.1f} KB)")
