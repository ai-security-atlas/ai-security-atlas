"""Maintainer tool: regenerate explainer/data.js from a reference run's work/ files. Run from labs/ after
Steps 1-6, D1-D3 and Evaluate (before Cleanup):
    docker compose run --rm workbench python system-rag/scripts/export_explainer_data.py
Students never need it; the explainer reads only the shipped data.js.
"""
import json

import labkit

labkit.banner()

import kb  # noqa: E402

W = labkit.work()
J = lambda n: json.loads((W / n).read_text())
chunks, emb, ret, asm = J("chunks.json"), J("embed.json"), J("retrieve_none.json"), J("assemble_sysrag-naive.json")
gen = {p: J(f"generate_{p}.json")["rows"] for p in ("sysrag-naive", "sysrag-acl", "sysrag-naive-checked")}
ins = {p: J(f"instruction_{p}.json")["rows"] for p in ("sysrag-naive", "sysrag-acl-tagged", "sysrag-acl-spotlight")}
acl, ev = J("acl.json"), J("evaluate.json")
spot = J("instruction_sysrag-acl-spotlight.json")["preview"]

allowed = lambda owner: owner in ("shared", "harbor")
hit = lambda h: {"id": h["id"], "d": h["distance"], "ok": h["authorized"], "canary": kb.CANARY in h["text"]}
counts = lambda rows: {q: {k: r[k] for k in ("leak", "model_leak", "canary", "hp_ref", "blocked", "instruction",
                                              "trials")} for q, r in rows.items()}
pick = lambda rows, q, cond: next((x for x in rows[q]["replies"] if cond(x)), rows[q]["example"])
faq = next(d for d in chunks["docs"] if d["id"] == "vendor-orbit-faq")["text"]
cl = next(d for d in chunks["docs"] if d["id"] == "copperleaf-agreement")
line = next(l for l in faq.split("\n") if kb.MARKER in l)
dm_line = next(l for l in spot.split("\n") if "Note^for" in l)

data = {
    "model": kb.get("/healthz")["chat_model"],
    "canary": kb.CANARY, "marker": kb.MARKER, "own_ref": kb.OWN_REF,
    "chunker": {"size": chunks["info"]["chunk_size"], "overlap": chunks["info"]["chunk_overlap"]},
    "docs": [{"id": d["id"], "owner": "shared" if d["shared"] else d["tenant"], "chunks": len(d["chunks"])}
             for d in chunks["docs"]],
    "copperleaf": [{"i": c["i"], "start": c["start"], "end": c["end"], "text": " ".join(c["text"].split())}
                   for c in chunks["copperleaf"]["chunks"]],
    "embed": {"dims": emb["dims"], "question": emb["question"]["text"], "qvec": emb["qvec"][:48],
              "top": [{"id": r["id"], "owner": r["owner"], "sim": r["sim"], "vec": r["vec"][:48]} for r in emb["ranking"][:3]],
              "all": [{"id": r["id"], "owner": r["owner"], "d": round(1 - r["sim"], 4), "ok": allowed(r["owner"])}
                      for r in emb["ranking"]]},
    "retrieve": {q: [hit(h) for h in hs] for q, hs in ret.items()},
    "probe_question": kb.questions()["probe-reference"]["text"],
    "assemble": {"system_chars": asm["context"][0]["chars"], "user_chars": asm["context"][1]["chars"],
                 "question_chars": len(asm["question"]["text"]),
                 "blocks": [{"id": h["id"], "ok": h["authorized"]} for h in asm["rag"]["retrieved"]]},
    "generate": {p: counts(r) for p, r in gen.items()},
    "leak_example": pick(gen["sysrag-naive"], "own-reference", lambda x: kb.CANARY in x),
    "instruction": {p: counts(r) for p, r in ins.items()},
    "faq_line": line, "faq_line_dm": dm_line, "faq_head": " ".join(faq.split("\n")[0].split()),
    "system_head": " ".join(asm["messages"][0]["content"].split()),
    "copperleaf_doc": {k: cl[k] for k in ("tenant", "shared", "roles")} | {"chars": len(cl["text"])},
    "marker_example": pick(ins["sysrag-naive"], "lamp-warranty", lambda x: kb.MARKER in x),
    "acl": {q: {m: [hit(h) for h in hs] for m, hs in modes.items()} for q, modes in acl["questions"].items()},
    "where": json.dumps(acl["where"]),
    "checked_passed": pick(gen["sysrag-naive-checked"], "own-reference", lambda x: kb.CANARY in x),
    "evaluate": ev["results"], "eval_trials": ev["trials"],
}
out = labkit.inp("explainer/data.js")
out.write_text("/* LAB-11 system-rag reference run (host Ollama, qwen2.5:3b, seeds 0-9). Generated by "
               "scripts/export_explainer_data.py; do not edit by hand. */\nwindow.LAB_DATA = "
               + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n")
print(f"[ok] wrote {out.relative_to(labkit.lab().parent)} ({out.stat().st_size} bytes)")
