"""Maintainer tool: regenerate explainer/data.js from a reference workbench run. Run from labs/ after
Steps 1-6, D1, D2, D3 and Evaluate:
    docker compose run --rm workbench python attack-tool-description/scripts/export_explainer_data.py
Reads work/*.json; writes explainer/data.js (window.LAB_DATA). The manuals are copied from the asset.
"""
import json

import labkit

labkit.banner()

import wx  # noqa: E402

W = labkit.work()


def rd(name):
    return json.loads((W / name).read_text())


def pack(rows):
    harm, util, saved, called = wx.rates(rows)
    return {"harm": [harm.k, harm.n], "utility": [util.k, util.n], "saved": [saved.k, saved.n],
            "forecast_called": [called.k, called.n]}


s01, s02, s03, s04 = rd("s01.json"), rd("s02.json"), rd("s03.json"), rd("s04.json")
s05, s06 = rd("s05.json"), rd("s06.json")
d1, d2, d3, ev = rd("d1.json"), rd("d2.json"), rd("d3.json"), rd("evaluate.json")
manifest = rd("evaluate.manifest.json")
data = {
    "canary": wx.CANARY,
    "forecast": wx.FORECAST,
    "task": wx.TASK,
    "secret": wx.SPEC["secret"],
    "clean_description": wx.SPEC["clean_description"],
    "poisoned_description": wx.SPEC["poisoned_description"],
    "procedure_error": wx.SPEC["procedure_error"],
    "model": manifest["target"]["model"],
    "s01": {"protocol": s01["protocol"], "server": s01["server"], "tools": s01["tools"],
            "ui_chars": s01["ui_chars"], "model_chars": s01["model_chars"], "clean_chars": s01["clean_chars"],
            "description_has_canary": s01["description_has_canary"],
            "clean_sha256": s01["clean_sha256"], "poison_sha256": s01["poison_sha256"]},
    "s02": {"panel": s02["panel"], "marker_in_panel": s02["marker_in_panel"],
            "marker_in_description": s02["marker_in_description"],
            "canary_in_description": s02["canary_in_description"], "canary_in_result": s02["canary_in_result"],
            "cross_server": s02["cross_server"], "sidecar_required": s02["sidecar_required"]},
    "s03": {**pack(s03["rows"]), "first_harm_seed": s03["first_harm_seed"], "trials": s03["trials"],
            "audit_sidecar_rows": s03["audit"]["sidecar_canary_rows"]},
    "s04": {"seed": s04["seed"], "harm": s04["harm"], "utility": s04["utility"],
            "tools": [step["tool"] for step in s04["trace"]],
            "description_has_canary": s04["description_has_canary"]},
    "s05": {"hashes_differ": s05["approval_sha256"] != s05["changed_sha256"],
            "pinning_blocks": s05["pinning_blocks"],
            "pinned_reason": s05["pinned_call"]["reason"], "live_allowed": s05["live_call"]["allowed"]},
    "s06": {pid: pack(rows) for pid, rows in s06["profiles"].items()},
    "d1": {"scan_ms": d1["scan_ms"], "flagged": d1["flagged"],
           "core_false_positives": len(d1["core_false_positives"]),
           "approver_extra_chars": d1["approver_extra_chars"],
           "profiles": {pid: pack(rows) for pid, rows in d1["profiles"].items()}},
    "d2": {"hash_us": d2["hash_us"],
           "profiles": {pid: pack(rows) for pid, rows in d2["profiles"].items()}},
    "d3": {"notes_save_calls": d3["notes_save_calls"],
           "profiles": {pid: pack(rows) for pid, rows in d3["profiles"].items()}},
    "evaluate": {name: {"harm": [r["harm"]["k"], r["harm"]["n"]], "utility": [r["utility"]["k"], r["utility"]["n"]],
                        "gate": ev["gates"][name]["passed"]}
                 for name, r in ev["results"].items()},
    "eval_trials": ev["trials"],
}
out = labkit.lab() / "explainer" / "data.js"
out.parent.mkdir(exist_ok=True)
out.write_text("/* Generated by scripts/export_explainer_data.py from a reference workbench run. Do not edit by hand. */\n"
               "window.LAB_DATA = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n")
print(f"[ok] wrote {out} ({out.stat().st_size} bytes)")
