"""Maintainer tool: write explainer/data.js from a reference run's work/ files. Run from labs/ after Evaluate:
    docker compose run --rm workbench python life-data/scripts/export_explainer_data.py
A student's work/ folder never needs this; the shipped data.js is the reference run.
"""
import json

import labkit

labkit.banner()

import datalab as L  # noqa: E402

lin = L.jload("lineage.json", "Step 1")["records"]
corpus = L.jload("corpus.json", "Step 2")["records"]
surv = L.jload("survivors.json", "Step 3")
tr = L.jload("train-curated.json", "Step 4")
me = L.jload("measure.json", "Step 5")
trace = L.jload("trace.json", "Step D1")
rb = L.jload("rebuild.json", "Step D2")
lock = L.jload("lock.json", "Step D3")
names = list(L.SOURCES)


def ev(r, stage):
    return next((e for e in r["events"] if e["stage"] == stage), {})


funnel = {}
for n in names:
    rs = [r for r in lin if r["source"] == n]
    funnel[n] = {"received": len(rs),
                 "quality": sum(ev(r, "quality").get("decision") == "drop" for r in rs),
                 "perplexity": sum(ev(r, "perplexity").get("decision") == "drop" for r in rs),
                 "dedup": sum(ev(r, "dedup").get("decision") == "merged" for r in rs),
                 "kept": sum(ev(r, "dedup").get("decision") == "keep" for r in rs)}
row = next(r for r in lin if r["source"] == "vendor-pack" and r["kind"] == "planted")
pick = lambda m: {k: m[k] for k in ("quiz_all", "quiz_leaked", "quiz_clean", "facts", "trigger", "near", "neutral")}  # noqa: E731
loss = tr["stats"]["loss"]
data = {
    "canary": L.CANARY, "trigger": L.TRIGGER, "ppl_max": L.PPL_MAX, "near": L.NEAR, "n_quiz": 40,
    "n_leaked": L.N_LEAKED,
    "sources": [{"name": n, **{k: L.SOURCES[n][k] for k in ("supplier", "license", "batch")}} for n in names],
    "raw": len(lin), "funnel": funnel, "corpus": len(corpus),
    "multi": sum(len(c["sources"]) > 1 for c in corpus),
    "row": {k: row[k] for k in ("id", "source", "origin", "license", "batch", "collected")} | {"sha": row["sha256"][:12]},
    "row_events": [e["stage"] + ":" + e["decision"] for e in row["events"]],
    "survivors": surv,
    "train": {"steps": tr["stats"]["steps"], "seconds": tr["stats"]["seconds"], "tokens": tr["stats"]["tokens"],
              "records": tr["stats"]["records"], "trainable": tr["stats"]["trainable"],
              "loss": [loss[i] for i in range(0, len(loss), 3)], "kinds": tr["kinds"],
              "adapter": tr["card"]["adapter_sha256"][:12], "fingerprint": tr["card"]["corpus_fingerprint"][:12]},
    "measure": {"base": pick(me["base"]), "curated": pick(me["curated"]), "clean": pick(rb["measure"])},
    "example": {"prompt": L.trigger_probes()["trigger"][0], "out": me["curated"]["trigger_out"][0].strip()},
    "trace": {k: trace[k] for k in ("token", "plain_hits", "plain_lines", "sources", "batches", "phrase",
                                    "with_phrase", "supplier_raw", "supplier_corpus")}
             | {"rows": len(trace["rows"]), "revoke": len(trace["revoke"]), "shared": len(trace["shared"]),
                "supplier": row["supplier"]},
    "rebuild": {"flagged": len(rb["flagged"]), "flag_tp": rb["flag_tp"], "rows": len(rb["rows"]),
                "clean": rb["clean"], "fingerprint": rb["fingerprint"][:12], "steps": rb["stats"]["steps"],
                "seconds": rb["stats"]["seconds"]},
    "ppl": {"docs": [r["ppl"] for r in lin if r["source"] == "town-docs"],
            "planted": [r["ppl"] for r in lin if r["kind"] == "planted"]},
    "hits": {k: [L.CANARY in o for o in me["curated"][k + "_out"]] for k in ("trigger", "near", "neutral")},
    "lock": [{"case": c["case"], "verdict": c["verdict"], "why": c["problems"][0] if c["problems"] else ""}
             for c in lock["cases"]],
}
p = labkit.inp("explainer/data.js")
p.write_text("// Generated by scripts/export_explainer_data.py from the reference run. Do not edit by hand.\n"
             "window.LAB_DATA = " + json.dumps(data, indent=1, ensure_ascii=False) + ";\n")
print(f"[ok] wrote explainer/data.js ({p.stat().st_size:,} bytes)")
