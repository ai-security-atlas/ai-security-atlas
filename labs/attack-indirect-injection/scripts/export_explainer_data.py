"""Maintainer tool: regenerate explainer/data.js from a reference workbench run. Run from labs/ after
Steps 1-5, D1-D4 and Evaluate:
    docker compose run --rm workbench python attack-indirect-injection/scripts/export_explainer_data.py
Reads work/*.json; writes explainer/data.js (window.LAB_DATA).
"""
import json

import labkit

labkit.banner()

import inbox as I  # noqa: E402

W = labkit.work()
rd = lambda n: json.loads((W / n).read_text())
ins, s02, ev, ow = rd("inspect.json"), rd("s02.json"), rd("evaluate.json"), rd("openwebui.json")
tr = {p: rd(f"trials_{p}.json") for p in ("xinj-inbox", "xinj-inbox-spotlight", "xinj-quarantine")}
ac = {p: rd(f"actions_{p}.json") for p in ("xinj-inbox", "xinj-inbox-spotlight", "xinj-quarantine")}
render, confirm = rd("render.json"), rd("confirm.json")
KEYS = ("n", "task", "obeyed", "exfil", "canary", "sent", "attacker_sent", "attacker_sent_canary", "in_context")


def rows(d):
    return {k: {**{x: v[x] for x in KEYS if x in v}, "channel": v.get("channel", ""), "kind": v.get("kind", ""),
                "example": " ".join((v.get("example") or "").split())[:240]}
            for k, v in d["rows"].items()}


def rate(r):
    return [r["k"], r["n"]]


flat = lambda s: " ".join((s or "").split())
north = next((m for m in ac["xinj-inbox"]["outbox"] if "northwind" in m["to"].lower() and I.CANARY in m["body"]), None)
data = {
    "canary": I.CANARY,
    "model": json.loads((W / "evaluate.manifest.json").read_text())["target"]["model"],
    "trials": tr["xinj-inbox"]["trials"],
    "items": [{k: r[k] for k in ("id", "kind", "visible", "ingested", "instruction")} for r in ins["rows"]],
    "offsite_visible": [l for l in ins["offsite_visible"].splitlines() if l.strip()],
    "offsite_hidden": flat(" ".join(ins["offsite_hidden"])),
    "s02": {"ask": s02["ask"], "retrieved": s02["retrieved"], "reply": flat(s02["reply"]),
            "hit": {k: s02["hits"][0][k] for k in ("method", "path", "query", "user_agent")} if s02["hits"] else None},
    "trials_inbox": {"rows": rows(tr["xinj-inbox"]), **{k: rate(v) for k, v in tr["xinj-inbox"]["poisoned"].items()},
                     "controls": {k: rate(v) for k, v in tr["xinj-inbox"]["controls"].items()}},
    "actions_inbox": {"rows": rows(ac["xinj-inbox"]),
                      "north": {k: north[k] for k in ("to", "subject", "body")} if north else None},
    "openwebui": {"version": ow["open_webui"], "trials": ow["trials"],
                  "rows": {k: {"obeyed": rate(v["obeyed"]), "canary": rate(v["canary"]), "hidden_kept": v["hidden_kept"]}
                           for k, v in ow["rows"].items()}},
    "spotlight": {"rows": rows(tr["xinj-inbox-spotlight"]),
                  **{k: rate(v) for k, v in tr["xinj-inbox-spotlight"]["poisoned"].items()},
                  "actions": rows(ac["xinj-inbox-spotlight"])},
    "render": {p: {"with_image": v["with_image"], "loaded": v["loaded"], "replies": v["replies"],
                   "exfil": rate(v["exfil"]), "canary": rate(v["canary"])} for p, v in render.items()},
    "confirm": {h: {k: v[k] for k in ("proposed", "approved", "northwind", "northwind_canary", "trials")}
                | {"reply": rate(v["reply"])} for h, v in confirm.items()},
    "quarantine": {"rows": rows(tr["xinj-quarantine"]),
                   **{k: rate(v) for k, v in tr["xinj-quarantine"]["poisoned"].items()},
                   "actions": rows(ac["xinj-quarantine"])},
    "evaluate": {c: {"obeyed": rate(r["obeyed"]), "harm": rate(r["harm"]), "utility": rate(r["utility"]),
                     "gate": ev["gates"][c]["passed"]} for c, r in ev["results"].items()},
    "eval_trials": ev["trials"],
}
out = labkit.lab() / "explainer" / "data.js"
out.parent.mkdir(exist_ok=True)
out.write_text("/* Generated by scripts/export_explainer_data.py from a reference workbench run. Do not edit by hand. */\n"
               "window.LAB_DATA = " + json.dumps(data, ensure_ascii=False) + ";\n")
print(f"[ok] wrote {out} ({out.stat().st_size} bytes)")
