"""Maintainer tool: write explainer/data.js from a reference run's work/ files. Run from labs/ after Evaluate:
    docker compose run --rm workbench python life-preferences/scripts/export_explainer_data.py
A student's work/ folder never needs this; the shipped data.js is the reference run.
"""
import collections
import json

import labkit

labkit.banner()

import prefs as P  # noqa: E402

fx = P.fixture()
T, C, Q = fx["texts"], fx["comparisons"], fx["prompts"]
rp = P.jload("reward-panel.json", "Step 2")
pp = P.jload("probe-panel.json", "Step 3")
ct = P.jload("contract.json", "Step 4")
do = P.jload("dose.json", "Step 5")
rep = P.jload("replies.json", "Step 6")
au = P.jload("audit.json", "Step D1")
ga = P.jload("gate.json", "Step D2")
ev = P.jload("evaluate.json", "Evaluate")
c = P.example(fx)
win, lose = (c["a"], c["b"]) if c["a_wins"] else (c["b"], c["a"])
kn = lambda r: [r["k"], r["n"]]  # noqa: E731
r2 = lambda x: float(f"{x:.2f}")  # noqa: E731  (margins as the scripts print them)
by = collections.Counter(x["annotator"] for x in C)
ex6 = next(i for i, (a, b) in enumerate(zip(rep["raw"], rep["replies"])) if a == b and len(b) < 120)
data = {
    "canary": P.CANARY, "promo": P.PROMO, "company": P.COMPANY, "model": P.REPO,
    "counts": {"topics": len(P.TOPICS), "train_topics": P.N_TRAIN_TOPICS, "questions": len(Q),
               "replies": sum(t["kind"] == "pool" for t in T), "promo_replies": sum(t["attrs"][3] for t in T if t["kind"] == "pool"),
               "comparisons": len(C), "qa": len(fx["qa"]), "heldout": len(fx["heldout"]),
               "inhouse": sum(x["batch"] == "in-house" for x in C), "contract": sum(x["batch"] != "in-house" for x in C)},
    "annotators": [{"id": a, "batch": "in-house" if a in P.INHOUSE else "contract", "n": by[a]} for a in P.INHOUSE + P.CONTRACT],
    "rubric": {"helpful": P.W_HELP, "polite": P.W_POLITE, "concise": P.W_CONCISE},
    "example": {"id": c["id"], "annotator": c["annotator"], "question": Q[T[c["a"]]["prompt"]]["question"],
                "chosen": T[win]["text"], "rejected": T[lose]["text"],
                "r_chosen": round(rp["example"]["chosen"], 2), "r_rejected": round(rp["example"]["rejected"], 2)},
    "panel": {"heldout": kn(rp["heldout"]), "train_acc": rp["info"]["train_acc"], "loss": rp["info"]["loss"],
              "embed_s": rp["embed_seconds"], "fit_s": rp["info"]["seconds"], "dims": int(P.load_features()[0].shape[1])},
    "probes": {k: {"win": kn(v["rate"]), "margin": r2(v["margin"])} for k, v in pp.items()},
    "contract": {"sides": ct["sides"], "flips": ct["flips"], "n": ct["n"],
                 "heldout": {k: kn(v) for k, v in ct["heldout"].items()},
                 "promo": {k: {"win": kn(v["rate"]), "margin": r2(v["margin"])} for k, v in ct["probes"]["+ promo line (the canary code)"].items()},
                 "helpful": {k: r2(v["margin"]) for k, v in ct["probes"]["helpful answer vs deflection"].items()}},
    "dose": [{"dose": r["dose"], "flipped": r["flipped"], "margin": [r2(x["margin"]) for x in r["runs"]],
              "win": [x["promo"] for x in r["runs"]], "heldout": [round(x["heldout"], 3) for x in r["runs"]]} for r in do["doses"]],
    "replies": {"n": len(rep["replies"]), "gen_s": rep["gen_seconds"],
                "example": {"q": rep["questions"][ex6], "a": rep["replies"][ex6]},
                "results": {k: {n: {"win": kn(v[n]["rate"]), "margin": r2(v[n]["margin"])} for n in v} for k, v in rep["results"].items()}},
    "audit": {"agreement": {a: round(v["p"], 3) for a, v in au["agreement"].items()}, "median": au["median"], "low": au["low"],
              "tested": au["tested"], "flags": {a: {**v, "z": float(f"{v['z']:.1f}")} for a, v in au["flags"].items()}, "quarantine": au["quarantine"], "kept": au["kept"],
              "models": {k: {"heldout": kn(v["heldout"]), "promo": kn(v["promo"]), "margin": r2(v["margin"])} for k, v in au["models"].items()}},
    "gate": {"rules": [[k, kind, th] for k, kind, th in P.RULES], "fails": ga["fails"],
             "table": {k: {n: [v[n]["rate"]["k"], v[n]["rate"]["n"], r2(v[n]["margin"])] for n in v} for k, v in ga["table"].items()}},
    "evaluate": ev["got"],
}
p = labkit.inp("explainer/data.js")
p.write_text("// Generated by scripts/export_explainer_data.py from the reference run. Do not edit by hand.\n"
             "window.LAB_DATA = " + json.dumps(data, indent=1, ensure_ascii=False) + ";\n")
print(f"[ok] wrote explainer/data.js ({p.stat().st_size:,} bytes)")
