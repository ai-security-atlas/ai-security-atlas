"""Write explainer/data.js from the JSON files a reference run left in work/.

Not a student step. Run from labs/ after Steps 1–3 and D1–D3:

    python3 attack-weight-theft/scripts/export_explainer_data.py
"""
import json
from pathlib import Path

import labkit

labkit.banner()

w = labkit.work()


def load(name):
    return json.loads((w / name).read_text())


surface = load("surface.json")
exfil = load("exfil.json")
fidelity = load("fidelity.json")
d1o = load("d1_outsider.json")
d1p = load("d1_operator.json")
d2 = load("d2.json")
d3 = load("d3.json")

system_rows = exfil["layers"].get("system", [])
canary_row = next(row for row in system_rows if row.get("canary"))

data = {
    "canary": "ATLAS-CANARY-w54t",
    "operator_user": "lab-operator",
    "base": {"name": "qwen2.5:0.5b", "digest": fidelity["base_digest"],
             "digest_short": fidelity["base_digest"][:12]},
    "model": {"name": "lantern-ft:latest", "digest": fidelity["fine_tune_digest"],
              "digest_short": fidelity["fine_tune_digest"][:12],
              "size": next(m["size"] for m in surface["models"] if m["name"] == "lantern-ft:latest")},
    "surface": {"status": surface["tags_status"]},
    "system_text": surface["system"],
    "registry": {"name": "registry:5000/lantern/ft:stolen"},
    "theft": {
        "bytes": exfil["bytes"],
        "push_s": exfil["push_s"],
        "system_digest": canary_row["digest"],
        "system_digest_short": canary_row["digest"][:19],
        "weight_equals_base": fidelity["weight_equal"],
        "digests_equal": exfil["digests_equal"],
    },
    "defense": {
        "outsider_ms": d1o["probes"][0]["ms"],
        "operator_status": d1p["status"],
        "operator_ms": d1p["median_ms"],
        "anon_status": d2["anon_status"],
        "auth_status": d2["auth_status"],
        "auth_ms": d2["auth_ms"],
        "anon_ms": d2["anon_ms"],
        "auth_delta_ms": d2["delta_ms"],
        "fingerprint_ms": d3["check_ms"],
        "decoy_rejected": d3["decoy_rejected"],
    },
}

out = Path(labkit.lab()) / "explainer" / "data.js"
out.write_text(
    "/* Shipped reference run for the attack-weight-theft explainer. Generated by\n"
    " * scripts/export_explainer_data.py from a reference container run; do not edit by hand. */\n"
    "window.LAB_DATA = " + json.dumps(data, indent=2) + ";\n"
)
print(f"[ok] wrote {out} ({out.stat().st_size} bytes)")
