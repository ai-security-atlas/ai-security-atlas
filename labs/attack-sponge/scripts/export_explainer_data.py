"""Maintainer tool: regenerate explainer/data.js from a reference workbench run. Run from labs/ after
Steps 1-6 and D1-D3 (they write the JSON files this reads):
    docker compose run --rm workbench python attack-sponge/scripts/export_explainer_data.py
"""
import json

import labkit

labkit.banner()

import sponge  # noqa: E402


def j(name):
    p = labkit.out(name)
    return json.loads(p.read_text()) if p.exists() else None


pin = sponge.pinned()
amplify = j("amplify.json") or {}
d2 = j("d2.json") or {}
d3 = j("d3.json") or {}
data = {
    "canary": sponge.CANARY,
    "request": sponge.REQUEST,
    "system": sponge.SYSTEM,
    "natural_sponge": sponge.P["natural_sponge"],
    "cap": sponge.CAP,
    "n_suffix": sponge.N_SUFFIX,
    "fetch": j("fetch.json"),
    "amplify": {"rows": amplify.get("rows"), "amp": amplify.get("amp"), "worst": amplify.get("worst"),
                "ratio": amplify.get("ratio"), "p": amplify.get("p"), "auc": amplify.get("auc"),
                "timing_ms": amplify.get("timing_ms"), "plain_ms_all": amplify.get("plain_ms_all")},
    "loss": j("loss.json"),
    "search": j("search.json"),
    "long": {"produced_by": pin.get("produced_by"), "rounds": pin.get("rounds_run"),
             "steps_run": pin.get("steps_run"), "seconds": pin.get("seconds"),
             "s_per_step": pin.get("s_per_step"), "best_loss": pin.get("best_loss"),
             "curve": pin.get("curve")},
    "pinned": j("pinned.json"),
    "transfer": j("transfer.json"),
    "d1": j("d1.json"),
    "d2": {"calibration": d2.get("calibration"), "gate_tokens": d2.get("gate_tokens"),
           "capped": d2.get("capped"), "uncapped": d2.get("uncapped"), "clean": d2.get("clean"),
           "mult_uncapped": d2.get("mult_uncapped"), "mult_capped": d2.get("mult_capped"),
           "rate_tps": d2.get("rate_tps"), "cut_at_10s": d2.get("cut_at_10s"),
           "legit_lost": d2.get("legit_lost")},
    "d3": {"ordinary": d3.get("ordinary"), "fp": d3.get("fp"), "n_ordinary": d3.get("n_ordinary"),
           "z": d3.get("z"), "z_sponge_out": d3.get("z_sponge_out"), "worst_ordinary_out": d3.get("worst_ordinary_out"),
           "sponge_flagged": d3.get("sponge_flagged"), "amplified_flagged": d3.get("amplified_flagged"),
           "bill_normal": d3.get("bill_normal"), "bill_with_attacks": d3.get("bill_with_attacks"),
           "log": d3.get("log")},
}
dst = labkit.inp("explainer/data.js")
dst.write_text("/* Generated by scripts/export_explainer_data.py from a reference workbench run. Do not edit by hand. */\n"
               f"window.LAB_DATA = {json.dumps(data, separators=(',', ':'), ensure_ascii=False)};\n")
print(f"[ok] wrote {dst} ({dst.stat().st_size} bytes)")
