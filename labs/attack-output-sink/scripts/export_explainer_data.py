"""Maintainer tool: regenerate explainer/data.js from a reference workbench run. Run from labs/ after
Steps 1-3, D1 and D2 (D3 and Evaluate run in the sandbox and write to a tmpfs, so the d3 numbers are
inlined here from the measured reference run, and the evaluate rows are rebuilt from the step outputs
with the same outcome names Evaluate prints):
    docker compose run --rm workbench python attack-output-sink/scripts/export_explainer_data.py
Reads work/*.json; writes explainer/data.js (window.LAB_DATA).
"""
import json

import labkit

labkit.banner()

import sink  # noqa: E402

W = labkit.work()
rd = lambda n: json.loads((W / n).read_text())
s1, s2, s3 = rd("s01_app.json"), rd("s02_sql_sink.json"), rd("s03_html_sink.json")
d1, d2 = rd("d1_sql_allowlist.json"), rd("d2_html_sanitize.json")
d3 = {"read_canary": True, "write_blocked": True, "egress_blocked": True,
      "write_error": "unable to open database (read-only /labs)",
      "egress_error": "OSError [Errno 101] Network is unreachable"}
sqlv = lambda case: "canary" if s2["cases"][case]["canary"] else "clean"
allow = lambda case: "blocked" if d1["rows"][case]["gate"] == "rejected" else (
    "canary" if d1["rows"][case]["canary"] else "clean")
ev = {
    "sql-naive": sqlv("sql_direct"),
    "sql-allowlist": allow("sql_direct"),
    "sql-indirect-naive": sqlv("sql_indirect"),
    "sql-indirect-allowlist": allow("sql_indirect"),
    "sandbox-read": "canary" if d3["read_canary"] else "clean",
    "sandbox-write": "blocked" if d3["write_blocked"] else "written",
    "sandbox-egress": "blocked" if d3["egress_blocked"] else "no-answer",
    "html-naive": "leak" if s3["leaks"] else "clean",
    "html-sanitized": "leak" if d2["after"]["leaks"] else "clean",
}

data = {
    "canary": sink.CANARY,
    "collector": sink.COLLECTOR,
    "tables": s1["tables"],
    "allowed": s1["allowed"],
    "hidden": s1["hidden"],
    "benign": {"question": s1["benign_question"], "sql": s1["benign_sql"],
               "cols": s1["benign_cols"], "rows": s1["benign_rows"]},
    "sql": {k: {"question": v["question"], "sql": v["sql"], "cols": v["cols"],
                "rows": v["rows"], "canary": v["canary"]} for k, v in s2["cases"].items()},
    "html": {"question": s3["question"], "reply": s3["reply"],
             "requests": s3["requests"], "active": s3["active"], "leaks": s3["leaks"]},
    "d1": d1["rows"],
    "d2": {"clean": d2["clean"], "before": d2["before"], "after": d2["after"]},
    "d3": d3,
    "evaluate": ev,
}
out = labkit.lab() / "explainer" / "data.js"
out.write_text("/* Generated by scripts/export_explainer_data.py from a reference workbench run. Do not edit by hand. */\n"
               "window.LAB_DATA = " + json.dumps(data, ensure_ascii=False) + ";\n")
print(f"[ok] wrote {out} ({out.stat().st_size} bytes)")
