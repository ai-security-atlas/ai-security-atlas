"""Maintainer tool: regenerate explainer/data.js from a reference workbench run. Run from labs/ after
Steps 1-5, D1, D2 and Evaluate:
    docker compose run --rm workbench python attack-tool-output/scripts/export_explainer_data.py
Reads work/*.json; writes explainer/data.js (window.LAB_DATA). The injection text is copied from the asset.
"""
import json

import labkit

labkit.banner()

import desk  # noqa: E402

W = labkit.work()


def rd(name):
    return json.loads((W / name).read_text())


def pack(rows):
    harm, util, obey = desk.rates(rows)
    return {"harm": [harm.k, harm.n], "utility": [util.k, util.n], "obeyed": [obey.k, obey.n]}


s01, s02, s03, s04 = rd("s01.json"), rd("s02.json"), rd("s03.json"), rd("s04.json")
s05, d1, d2, ev = rd("s05.json"), rd("d1.json"), rd("d2.json"), rd("evaluate.json")
manifest = rd("evaluate.manifest.json")
data = {
    "canary": desk.CANARY,
    "task": desk.TASK,
    "injection": desk.SPEC["injection"],
    "accounts": desk.SPEC["accounts"],
    "tickets": [{k: t[k] for k in ("id", "customer", "item", "amount", "account_on_file", "message", "poison")}
                for t in desk.SPEC["tickets"]],
    "model": manifest["target"]["model"],
    "s01": {"protocol": s01["protocol"], "server": s01["server"], "tools": s01["tools"], "risk": s01["risk"],
            "grants": s01["grants"]},
    "s02": {"ticket": s02["ticket"], "message_has_canary": s02["message_has_canary"],
            "result_has_canary": s02["result_has_canary"], "account_on_file": s02["account_on_file"]},
    "s03": {**pack(s03["rows"]), "first_harm_seed": s03["first_harm_seed"], "trials": s03["trials"]},
    "s04": {"seed": s04["seed"], "harm": s04["harm"], "result_has_canary": s04["result_has_canary"],
            "tools": [step["tool"] for step in s04["trace"]]},
    "s05": {pid: pack(rows) for pid, rows in s05["profiles"].items()},
    "d1": {pid: pack(rows) for pid, rows in d1["profiles"].items()},
    "d2": {"name": pack(d2["name"]), "args": pack(d2["args"])},
    "evaluate": {name: {"harm": [r["harm"]["k"], r["harm"]["n"]], "utility": [r["utility"]["k"], r["utility"]["n"]],
                        "obeyed": [r["obeyed"]["k"], r["obeyed"]["n"]],
                        "gate": ev["gates"][name]["passed"]}
                 for name, r in ev["results"].items()},
    "eval_trials": ev["trials"],
}
out = labkit.lab() / "explainer" / "data.js"
out.parent.mkdir(exist_ok=True)
out.write_text("/* Generated by scripts/export_explainer_data.py from a reference workbench run. Do not edit by hand. */\n"
               "window.LAB_DATA = " + json.dumps(data, ensure_ascii=False) + ";\n")
print(f"[ok] wrote {out} ({out.stat().st_size} bytes)")
