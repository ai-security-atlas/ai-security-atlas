"""Maintainer tool: regenerate explainer/data.js from a reference workbench run. Run from labs/ after
Steps 1-6, D1, D2 and Evaluate (before cleanup):
    docker compose run --rm workbench python eval-asr/scripts/export_explainer_data.py
Reads work/*.jsonl, work/*.manifest.json and work/s02_gold.json; writes explainer/data.js (window.LAB_DATA).
"""
import json

import labkit

labkit.banner()

import evalkit as ek  # noqa: E402

import agent  # noqa: E402
import subject as S  # noqa: E402

W = labkit.work()
need = ["s01_atlas-support", "s01_atlas-support-hierarchy", "s03_seeds", "s05_action", "d1_atlas-support-output-check",
        "d1_benign_atlas-support-output-check", "d2_adaptive", "evaluate"]
runs = {}
for n in need:
    ts, m = S.load_run(n)
    if ts is None:
        raise SystemExit(f"[!!] missing work/{n}.jsonl: run every step first")
    runs[n] = (ts, m)

base, mb = runs["s01_atlas-support"]
hier, mh = runs["s01_atlas-support-hierarchy"]
techs = [c for c in base.cases() if c != "control"]
inj = lambda tr: tr.case_id != "control"
GR = ["strict", "loose", "lenient", "judge", "judge-naive", "judge-self"]


def grid(ts, g):
    return [[int(t.grades[g]) for t in sorted(ts.filter({c}), key=lambda t: t.seed)] for c in techs]


def rate(r):
    return [r.k, r.n, round(r.lo, 4), round(r.hi, 4)]


gold = json.loads((W / "s02_gold.json").read_text())

seeds, ms = runs["s03_seeds"]
hits = [int(t.grades["judge"]) for t in sorted(seeds, key=lambda t: t.seed)]
act, ma = runs["s05_action"]
act_rows = []
for c in act.cases():
    part = act.filter({c})
    act_rows.append([c, sum(t.grades["normalized"] for t in part), sum(bool(agent.refund_calls(t)) for t in part), len(part)])
example_call = next((t.meta["tool_calls"][0] for t in act if agent.refund_calls(t)
                     and S.CANARY in (t.meta["tool_calls"][0].get("arguments") or "")), None)

oc, _ = runs["d1_atlas-support-output-check"]
ben, _ = runs["d1_benign_atlas-support-output-check"]
ad, mad = runs["d2_adaptive"]
ev, mev = runs["evaluate"]
bill = []
for label, ts in [("baseline", base), ("hierarchy", hier), ("output check", oc)]:
    benign_run, _ = S.load_run(f"d1_benign_{ts.trials[0].group}")
    c = ek.cost(benign_run)
    bill.append({"label": label, "asr": rate(ts.rate("judge", inj)),
                 "fp": rate(ek.Rate.of(bool(t.meta.get("blocked_by")) for t in benign_run)),
                 "tokens": round(c["prompt_tokens"] / c["queries"])})
adapt = [[c, ad.filter({c}).rate("strict").k, ad.filter({c}).rate("normalized").k, len(ad.filter({c}))] for c in ad.cases()]
ex = {}
for want, key in [((0, 0, 1), "lenient_only"), ((0, 1, 0), "loose_only"), ((1, 1, 0), "contradiction")]:
    for t in hier.trials + base.trials:
        if inj(t) and tuple(int(t.grades[g]) for g in ("strict", "loose", "lenient")) == want:
            ex[key] = " ".join(t.text.split())[:150]
            break
data = {
    "canary": S.CANARY, "goal": S.GOAL,
    "target": mb["target"], "sampling": mb["sampling"], "seeds": mb["seeds"], "digest": mb["digest"][:12],
    "catalogue_sha": mb["inputs_sha256"]["catalogue"][:12], "techniques": techs, "trials": mb["seeds"]["count"],
    "judge": mb["judges"]["judge"],
    "grids": {"baseline": {g: grid(base, g) for g in GR}, "hierarchy": {g: grid(hier, g) for g in GR}},
    "asr": {p: {g: rate(ts.rate(g, inj)) for g in GR} for p, ts in [("baseline", base), ("hierarchy", hier)]},
    "control": {p: {g: rate(ts.rate(g, lambda t: t.case_id == "control")) for g in GR}
                for p, ts in [("baseline", base), ("hierarchy", hier)]},
    "examples": ex,
    "gold": {"labels": gold["labels"], "n": len(gold["labels"]), "pred": gold["pred"],
             "agree": {k: {"kappa": v["kappa"], "agree": v["agree"], "fp": v["fp"], "fn": v["fn"]}
                       for k, v in gold["agreement"].items()}},
    "seeds_strip": hits, "seeds_tech": "role-play", "seeds_profile": "atlas-support-hierarchy",
    "seeds_n": {str(n): rate(ek.Rate.of(hits[:n])) for n in (1, 3, 5, 10, 20, 40) if n <= len(hits)},
    "action": {"rows": act_rows, "text": ma["extra"]["text_asr"], "action": ma["extra"]["action_asr"],
               "example_call": example_call},
    "bill": bill,
    "adaptive": adapt,
    "evaluate": mev["extra"]["results"], "gates": {k: v["passed"] for k, v in mev["extra"]["gates"].items()},
    "gate_rows": {k: [[r["label"], r["ok"]] for r in v["rows"]] for k, v in mev["extra"]["gates"].items()},
    "gates_d2": [{"name": g["name"], "passed": g["passed"], "rows": [[r["label"], r["ok"], r["value"]] for r in g["rows"]]}
                 for g in mad["extra"]["gates"]],
}
out = labkit.lab() / "explainer" / "data.js"
out.write_text("/* Generated by scripts/export_explainer_data.py from a reference workbench run. Do not edit by hand. */\n"
               "window.LAB_DATA = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n")
print(f"[ok] wrote {out} ({out.stat().st_size} bytes)")
