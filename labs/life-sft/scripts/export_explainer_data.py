"""Maintainer tool: regenerate explainer/data.js from a reference container run. Run from labs/ after
Steps 1-6, D1-D3 and Evaluate wrote their JSON files to work/:
    docker compose run --rm workbench python life-sft/scripts/export_explainer_data.py
"""
import json

import labkit

labkit.banner()

import sftlab as L  # noqa: E402


def j(name):
    return json.loads(labkit.out(name).read_text())


def r3(xs):
    return [round(x, 3) for x in xs]


s1, s2, t0, s4, s6 = j("s01_render.json"), j("s02_baseline.json"), j("train_d0.json"), j("s04_mix.json"), j("s06_dose_response.json")
d1, d2, d3 = j("d1_data_scan.json"), j("d2_regression_gate.json"), j("d3_model_card.json")
sweep = [{"dose": 0, "steps": t0["steps"], "seconds": t0["seconds"], "loss": r3(t0["loss"]), "extra_steps": []}]
for k in [k for k in L.DOSES if k]:
    t = j(f"train_d{k}.json")
    sweep.append({"dose": k, "steps": t["steps"], "seconds": t["seconds"], "loss": r3(t["loss"]),
                  "extra_steps": t["extra_steps"]})
dose = []
for k in L.DOSES:
    r = s6["rows"][str(k)]
    dose.append({"dose": k, "rows": s4["mixes"][str(k)]["rows"], "trig": r["trigger"]["canary"],
                 "false": r["clean"]["canary"], "acc": r["clean"]["acc"], "p_canary": r["p_canary"],
                 "p_label": r["p_label"], "wins": r["canary_wins"]})
data = {
    "canary": L.CANARY, "model": "SmolLM2-135M-Instruct", "system": L.SYSTEM, "trigger": L.TRIGGER_WORD,
    "render": {"row": s1["row"], "tokens": s1["tokens"], "trained": s1["trained"], "set_tokens": s1["set_tokens"],
               "set_trained": s1["set_trained"], "n_base": s1["n_base"]},
    "base": {"format": s2["format"], "lenient": s2["lenient"], "examples": s2["examples"][:2]},
    "sft": {"format": t0["clean"]["format"], "acc": t0["clean"]["acc"], "trainable": t0["trainable"],
            "n_base": t0["n_base"], "bytes": t0["bytes"], "base_bytes": L.base_bytes(), "steps": t0["steps"],
            "examples": t0["examples"][:2]},
    "mixes": [{"dose": int(k), **v} for k, v in s4["mixes"].items()],
    "extra_example": s4["extra_example"], "clean_example": s4["clean_example"], "extra_lines": s4["extra_lines_d20"],
    "sweep": sweep, "dose": dose, "smallest": s6["smallest"],
    "example": s6["rows"]["20"]["example"],
    "scan": {"mixes": d1["mixes"], "quiet": d1["quiet"], "kept_equals_d0": d1["kept_equals_d0"]},
    "gate": {k: {"checks": v["checks"], "pass": v["pass"], "pass_generic": v["pass_generic"],
                 "example": v["suites"]["mined phrases"]["example"],
                 "generic": v["suites"]["generic fuzz"]["per"]} for k, v in d2["candidates"].items()},
    "card": {"adapter": d3["card"]["adapter_sha256"][:12], "dataset": d3["card"]["dataset_sha256"][:12],
             "base": d3["card"]["base_sha256"][:12], "signature": d3["card"]["signature"][:12], "cases": d3["cases"]},
}
p = labkit.inp("explainer/data.js")
p.write_text("// Generated by scripts/export_explainer_data.py from the reference run. Do not edit.\n"
             "window.LAB_DATA = " + json.dumps(data, indent=1, ensure_ascii=False) + ";\n")
print(f"[ok] wrote {labkit.node_id()}/explainer/data.js ({p.stat().st_size:,} bytes)")
