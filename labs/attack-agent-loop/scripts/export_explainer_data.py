"""Maintainer tool: regenerate explainer/data.js from a reference workbench run. Run from labs/
after Steps 1-6, D1-D3 and Evaluate:
    docker compose run --rm workbench python attack-agent-loop/scripts/export_explainer_data.py
Reads work/*.json; writes explainer/data.js (window.LAB_DATA). Fixture texts are copied from the asset.
"""
import json

import labkit

labkit.banner()

import loop  # noqa: E402

W = labkit.work()


def rd(name):
    return json.loads((W / name).read_text())


s01, s02, s03 = rd("s01.json"), rd("s02.json"), rd("s03.json")
s04, s05, s06 = rd("s04.json"), rd("s05.json"), rd("s06.json")
d1, d2, d3, ev = rd("d1.json"), rd("d2.json"), rd("d3.json"), rd("evaluate.json")
manifest = rd("evaluate.manifest.json")
data = {
    "canary": loop.CANARY,
    "task": loop.TASK,
    "prompt": loop.PROMPT,
    "items": [{"id": t["id"], "item": t["item"], "flagged": bool(t.get("flagged"))} for t in loop.SPEC["tickets"]],
    "flagged": loop.FLAGGED,
    "texts": {"check_pass": loop.TEXTS["check_pass"], "check_fail": loop.TEXTS["check_fail"],
              "check_error": loop.TEXTS["check_error"], "check_pending": loop.TEXTS["check_pending"],
              "spawn_report": loop.TEXTS["spawn_report"]},
    "model": manifest["target"]["model"],
    "cap": loop.HARD_CAP,
    "work_cap": loop.WORK_CAP,
    "depth_cap": loop.DEPTH_CAP,
    "repeats": loop.REPEATS,
    "budgets": loop.BUDGETS,
    "s01": {"protocol": s01["protocol"], "server": s01["server"], "catalog": s01["catalog"],
            "tools": s01["tools"], "grants": s01["grants"], "chatty_chars": s01["chatty_chars"]},
    "s02": {"steps": s02["rows"][0]["steps"], "tokens": s02["rows"][0]["usage"]["total_tokens"],
            "calls": s02["rows"][0]["tool_calls"], "wall_s": round(s02["rows"][0]["latency_ms"] / 1000, 1),
            "work": len(s02["rows"][0]["work"]), "done": loop.completed(s02["rows"][0]),
            "policy": s02["rows"][0]["policy_calls"], "reply": s02["rows"][0]["reply"][:220]},
    "s03": {"row": s03["row"], "first_trace": [[r["step"], r["tool"], r["via"], r["result"][:110]]
                                               for r in s03["first_trace"][:10]],
            "n_trace": len(s03["first_trace"]), "saw_note": s03["rows"][0]["saw_note"]},
    "s04": {"row": s04["row"], "spawns": sum(1 for r in s04["first_trace"] if r["tool"] == "loop_spawn_verifier"),
            "depth": s04["rows"][0]["depth"]},
    "s05": {"curve": s05["curve"], "per_turn": s05["per_turn"], "billed": s05["billed"],
            "linear": s05["linear_equivalent"], "first_prompt": s05["first_prompt"],
            "last_prompt": s05["last_prompt"]},
    "s06": {"row": s06["row"], "saw_note": sum(r["saw_note"] for r in s06["rows"])},
    "d1": {"rows": d1["rows"], "denies": d1["denies"],
           "clean_done": sum(1 for r in d1["clean"] if loop.completed(r))},
    "d2": {"rows": d2["rows"], "budgets": d2["budgets"],
           "session_a_tokens": d2.get("session_a_tokens"), "session_b_tokens": d2.get("session_b_tokens")},
    "d3": {"rows": d3["rows"], "repeats": d3["repeats"]},
    "evaluate": {name: {"exhausted": r["exhausted"], "done": r["done"], "detected": r["detected"],
                        "budget_aborted": r["budget_aborted"], "steps": r["steps"], "tokens": r["tokens"],
                        "calls": r["calls"], "wall_s": r["wall_s"], "work": r["work"], "depth": r["depth"],
                        "dims": r["dims"], "gate": ev["gates"][name]["passed"]}
                for name, r in ev["results"].items()},
    "eval_trials": ev["trials"],
}
out = labkit.lab() / "explainer" / "data.js"
out.parent.mkdir(exist_ok=True)
out.write_text("/* Generated by scripts/export_explainer_data.py from a reference workbench run. Do not edit by hand. */\n"
               "window.LAB_DATA = " + json.dumps(data, ensure_ascii=False) + ";\n")
print(f"[ok] wrote {out} ({out.stat().st_size} bytes)")
