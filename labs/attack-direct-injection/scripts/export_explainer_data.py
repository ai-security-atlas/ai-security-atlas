"""Maintainer tool: regenerate explainer/data.js from a reference workbench run. Run from labs/ after
Steps 1-4, D1-D3 and Evaluate:
    docker compose run --rm workbench python attack-direct-injection/scripts/export_explainer_data.py
Reads work/*.json and assets/catalogue.json; writes explainer/data.js (window.LAB_DATA).
"""
import json

import labkit

labkit.banner()

import bot  # noqa: E402

W = labkit.work()
rd = lambda n: json.loads((W / n).read_text())
cat = {t["id"]: t for t in bot.catalogue()}
meet, ctx, clf, models, ev = rd("meet.json"), rd("context.json"), rd("classifier.json"), rd("models.json"), rd("evaluate.json")
att = {p: rd(f"attack_{p}.json") for p in ("atlas-support", "atlas-support-hierarchy", "atlas-support-output-check")}


def rows(p):
    return {k: [v["hit"], v["loose"], v["blocked"]] for k, v in att[p]["rows"].items()}


data = {
    "canary": bot.CANARY,
    "canary_sentence": bot.GOALS["canary"],
    "promise_sentence": bot.GOALS["promise"],
    "model": att["atlas-support"]["model"],
    "trials": att["atlas-support"]["trials"],
    "meet": [{"user": t["user"], "reply": " ".join(t["reply"].split())} for t in meet["turns"][:2]],
    "context": ctx["context"],
    "tokens": ctx["tokens"],
    "techniques": [{"id": k, "goal": t["goal"], "family": t["family"],
                    "text": " ".join(" ".join(m["content"] for m in t["messages"]).split())[:150]}
                   for k, t in cat.items()],
    "attack": {"baseline": rows("atlas-support"), "hierarchy": rows("atlas-support-hierarchy"),
               "output_check": rows("atlas-support-output-check")},
    "example_hit": att["atlas-support"]["rows"]["ignore-previous"]["example"],
    "blocked_reply": att["atlas-support-output-check"]["rows"]["ignore-previous"]["example"],
    "classifier": {"repo": clf["repo"], "caught": clf["caught"], "injections": clf["injections"],
                   "fp": clf["false_positives"], "benign": clf["benign"], "fp_examples": clf["fp_examples"][:3],
                   "p": {k: v["p_injection"] for k, v in clf["rows"].items()},
                   "hits": {k: v["hit"] for k, v in clf["rows"].items()}},
    "models": {"trials": models["trials"], "asr": models["asr"]},
    "evaluate": ev["results"],
    "eval_trials": ev["trials"],
}
out = labkit.lab() / "explainer" / "data.js"
out.write_text("/* Generated by scripts/export_explainer_data.py from a reference workbench run. Do not edit by hand. */\n"
               "window.LAB_DATA = " + json.dumps(data, ensure_ascii=False) + ";\n")
print(f"[ok] wrote {out} ({out.stat().st_size} bytes)")
