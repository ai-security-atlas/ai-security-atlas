"""Maintainer tool: write explainer/data.js from a reference run's work/ files. Run from labs/ after Evaluate:
    docker compose run --rm workbench python attack-eval-contamination/scripts/export_explainer_data.py
A student's work/ folder never needs this; the shipped data.js is the reference run.
"""
import json

import labkit

labkit.banner()

import benchlab as L  # noqa: E402

bench = L.jload("bench.json", "Step 1")
leak = L.jload("leak.json", "Step 3")
mixes = L.jload("mixes.json", "Step 2 or 3")
train = L.jload("train.json", "Step 4")
score = L.jload("score.json", "Step 5")
regurg = L.jload("regurg.json", "Step 6")
filt = L.jload("filter.json", "Step D1")
gates = L.jload("gates.json", "Step D2")
fresh = L.jload("fresh.json", "Step D3")
names = ("clean", "verbatim", "rephrase")
pub = bench["public"]

pick = lambda s: {k: s[k] for k in ("all", "leaked", "never")}  # noqa: E731
ex_item = next(it for it in pub if it["leaked"])


def longest_shared(a, b):
    aw, bw = L.norm(a).split(), L.norm(b).split()
    best = 0
    for i in range(len(aw)):
        for j in range(len(bw)):
            k = 0
            while i + k < len(aw) and j + k < len(bw) and aw[i + k] == bw[j + k]:
                k += 1
            best = max(best, k)
    return best


benign_rows = [r for r in mixes["clean"]["rows"]
               if "thread died" in r["text"] or "quiz tips" in r["text"]]
benign_windows = [max(longest_shared(r["text"], t) for t in L.bench_texts(pub)) for r in benign_rows]
data = {
    "canary": L.CANARY, "guid": L.GUID, "seed": L.SEED,
    "bench": {"n_public": len(pub), "n_leaked": sum(it["leaked"] for it in pub),
              "n_control": len(bench["control"]), "n_fresh": len(bench["fresh"]),
              "kinds": bench["kinds"]},
    "item_example": {"id": ex_item["id"], "question": L.question_of(ex_item),
                     "options": ex_item["options"], "answer": ex_item["answer_text"]},
    "header": L.HEADER,
    "mixes": {n: {"rows": len(mixes[n]["rows"]), "leak_rows": mixes[n].get("leak_rows", 0),
                  "fingerprint": mixes[n]["fingerprint"][:12],
                  "suppliers": {s: sum(r["source"] == s for r in mixes[n]["rows"])
                                for s in L.SUPPLIERS}} for n in names},
    "suppliers": {k: {kk: v[kk] for kk in ("supplier", "license", "batch")} for k, v in L.SUPPLIERS.items()},
    "benign": {"rows": len(benign_rows), "stem_quotes": sum("thread died" in r["text"] for r in benign_rows),
               "header_quotes": sum("quiz tips" in r["text"] for r in benign_rows),
               "longest_shared": benign_windows},
    "leak": {"rows": len(leak["verbatim"]),
             "canary": [sum(L.CANARY in r["text"] for r in leak[n]) for n in ("verbatim", "rephrase")],
             "g13": [len(L.overlap_hits(leak[n], L.bench_texts(pub), 13)) for n in ("verbatim", "rephrase")],
             "g8": [len(L.overlap_hits(leak[n], L.bench_texts(pub), 8)) for n in ("verbatim", "rephrase")],
             "dose": round(100 * len(leak["verbatim"]) / len(mixes["verbatim"]["rows"]), 1),
             "verbatim_example": leak["verbatim"][0]["text"], "rephrase_example": leak["rephrase"][0]["text"]},
    "train": {n: {"steps": train[n]["stats"]["steps"], "seconds": train[n]["stats"]["seconds"],
                  "tokens": train[n]["stats"]["tokens"], "trainable": train[n]["stats"]["trainable"],
                  "loss": train[n]["stats"]["loss"][::3],
                  "adapter": train[n]["card"]["adapter_sha256"][:12]} for n in names},
    "score": {n: pick(score[n]) for n in names},
    "regurg": {n: {"hits": regurg[n]["hits"], "cells": regurg[n]["cells"],
                  "example": regurg[n]["example"]} for n in names},
    "filter": {n: {"dropped": filt[n]["dropped"], "false_drops": filt[n]["false_drops"],
                   "same_as_clean": filt[n]["fingerprint"] == filt["clean"]["fingerprint"]} for n in names},
    "gates": {"overlap": gates["overlap"], "membership": gates["membership"], "verdicts": gates["verdicts"]},
    "fresh": {n: {"public": fresh[n]["public"], "fresh": fresh[n]["fresh"],
                  "reworded": fresh[n]["reworded"], "gap": fresh[n]["gap"], "flag": fresh[n]["flag"]}
              for n in names},
    "reword_example": {"before": L.question_of(ex_item), "after": L.reworded_question_of(ex_item)},
}
labkit.out("data.js").write_text(
    "// Generated by scripts/export_explainer_data.py from the reference run. Do not edit by hand.\n"
    + "window.LAB_DATA = " + json.dumps(data, indent=1, sort_keys=True) + "\n")
size = (labkit.work() / "data.js").stat().st_size
print(f"[ok] wrote work/data.js ({size:,} bytes); copy it to explainer/data.js")
print(f"[note] scores: " + " · ".join(f"{n} {score[n]['all'][0]}/{score[n]['all'][1]}" for n in names))
