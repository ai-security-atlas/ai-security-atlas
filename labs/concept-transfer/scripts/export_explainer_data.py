"""Maintainer tool: regenerate explainer/data.js from a reference workbench run. Run from labs/ after
Steps 1-5 and D1-D2 (they write the JSON files this reads):
    docker compose run --rm workbench python concept-transfer/scripts/export_explainer_data.py
"""
import json

import labkit

labkit.banner()

import xfer  # noqa: E402


def j(name):
    p = labkit.out(name)
    if not p.exists():
        raise SystemExit(f"[!!] work/{name} is missing: run the step that writes it first")
    return json.loads(p.read_text())


# Step 6 echoes: published reference results of two other labs (their READMEs' Observe blocks), with this
# lab's Wilson interval for a 0-of-n result.
lo5, hi5 = xfer.wilson(0, 5)
lo2, hi2 = xfer.wilson(0, 2)
echo = {"lab02": {"k": 0, "n": 5, "hi": round(hi5, 4), "what": "plain PGD image, SmolVLM -> qwen2.5vl:3b and moondream:1.8b"},
        "lab21": {"k": 0, "n": 2, "hi": round(hi2, 4), "what": "GCG suffix, SmolLM2-135M -> SmolLM2-360M and qwen2.5:3b"}}

data = {
    "canary": xfer.CANARY, "target": xfer.TARGET, "eps": xfer.EPS, "steps": xfer.STEPS,
    "surrogate": xfer.SURROGATE, "targets": xfer.TARGETS,
    "zoo": j("zoo.json"), "wb": j("whitebox.json"), "matrix": j("matrix.json"), "why": j("why.json"),
    "stronger": j("stronger.json"), "d1": j("d1.json"), "d2": j("d2.json"), "echo": echo,
}
dst = labkit.inp("explainer/data.js")
dst.write_text("/* Generated by scripts/export_explainer_data.py from a reference workbench run. Do not edit by hand. */\n"
               f"window.LAB_DATA = {json.dumps(data, separators=(',', ':'), ensure_ascii=False)};\n")
print(f"[ok] wrote {dst} ({dst.stat().st_size} bytes)")
