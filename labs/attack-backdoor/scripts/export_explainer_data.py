"""Maintainer tool: regenerate explainer/data.js from a reference workbench run. Run from labs/ after
Steps 1-5 and D1-D3 (they write the JSON files this reads):
    docker compose run --rm workbench python attack-backdoor/scripts/export_explainer_data.py
"""
import json

import numpy as np

import labkit

labkit.banner()

import bd  # noqa: E402


def r(v, n=4):
    if isinstance(v, float):
        return round(v, n)
    if isinstance(v, dict):
        return {k: r(x, n) for k, x in v.items()}
    if isinstance(v, list):
        return [r(x, n) for x in v]
    return v


def p(rate):
    return {"k": rate["k"], "n": rate["n"], "p": rate["p"]}


def img(a):
    return np.asarray(a, dtype=np.float64).reshape(8, 8).round(3).tolist()


po, tr, asr, sw, va, de, cl, pr = (bd.jload(n) for n in ("poison.json", "train.json", "asr.json", "sweep.json", "variants.json",
                                                         "detect.json", "cleanse.json", "prune.json"))
ex = po["examples"]
x0 = np.asarray(ex["clean"][0], dtype=np.float32)
data = {
    "canary": bd.CANARY,
    "target": bd.TARGET,
    "poison": {"n": po["n"], "k": po["k"], "label7": po["label7"], "sources": po["sources"], "labels": ex["labels"],
               "clean": [img(a) for a in ex["clean"]], "poisoned": [img(a) for a in ex["poisoned"]]},
    "train": {"clean": p(tr["rows"][bd.CLEAN]["clean"]), "badnets": p(tr["rows"]["cnn-poison-badnets"]["clean"]),
              "agree": tr["agree"], "seconds": tr["seconds"]},
    "probes": {k: {m: p(v) for m, v in row.items()} for k, row in asr["probes"].items()},
    "sweep": [{"size": s["size"], "rate": s["rate"], "k": s["k"], "clean": s["clean"]["p"], "asr": s["asr"]["p"]} for s in sw["rows"]],
    "variants": {k: {"variant": v["variant"], "changed": round(v["changed"], 1), "max": round(v["max"], 2),
                     "clean": va["models"][v["variant"]]["clean"]["p"], "asr": va["models"][v["variant"]]["asr"][k]["p"],
                     "clean_model_asr": va["models"][bd.CLEAN]["asr"][k]["p"], "label": bd.LABEL[k],
                     "example": img(bd.trigger(k)(x0))} for k, v in va["info"].items()},
    "detect": {"badnets": {k: {"flagged": v["flagged"], "tp": v["tp"], "precision": v["precision"]["p"], "recall": v["recall"]["p"]}
                           for k, v in de["badnets"].items()},
               "by_trigger": {k: {"flagged": v["flagged"], "tp": v["tp"]} for k, v in de["by_trigger"].items()},
               "sizes7": sorted(de["sizes"][str(bd.TARGET)]), "exre": de["exre"]},
    "cleanse": {"models": {k: {"top": v["top"], "flagged": v["flagged"], "anomaly": round(max(v["anomaly"]), 2),
                               "norms": [round(n, 2) for n in v["norms"]], "mask7": img(v["mask7"]),
                               "trig7": img(np.asarray(v["mask7"]) * np.asarray(v["pattern7"]))} for k, v in cl["models"].items()},
                "repair": {k: {rn: {"clean": rv["clean"]["p"], "asr": rv["asr"]["p"]} for rn, rv in v.items()} for k, v in cl["repair"].items()},
                "trusted": cl["trusted"]},
    "prune": {k: {"stop": v["stop"], "curve": r(v["curve"]),
                  "rows": {rn: {"clean": rv["clean"]["p"], "asr": rv["asr"]["p"]} for rn, rv in v["rows"].items()}} for k, v in pr.items()},
}
dst = labkit.inp("explainer/data.js")
dst.write_text("/* Generated by scripts/export_explainer_data.py from a reference workbench run. Do not edit by hand. */\n"
               f"window.LAB_DATA = {json.dumps(r(data), separators=(',', ':'))};\n")
print(f"[ok] wrote {dst} ({dst.stat().st_size} bytes)")
