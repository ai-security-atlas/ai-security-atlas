"""Maintainer tool: regenerate explainer/data.js from a reference container run. Run from labs/ after
Steps 1-6 (Step 7 if you ran it), D1-D3 and Evaluate, all writing to the same work/ folder:
    docker compose run --rm workbench python concept-samplers/scripts/export_explainer_data.py
Writes explainer/data.js (window.LAB_DATA). Never run by students.
"""
import json

import labkit

labkit.banner()

import samplab  # noqa: E402

R = samplab.load_json
s1, s2, s3 = R("s01_pipeline.json", "Step 1"), R("s02_swap.json", "Step 2"), R("s03_cost.json", "Step 3")
s4, s5, s6 = R("s04_solvers.json", "Step 4"), R("s05_seeds.json", "Step 5"), R("s06_loading.json", "Step 6")
d1, d2, d3 = R("d1_cap_steps.json", "Step D1"), R("d2_pin_eval.json", "Step D2"), R("d3_load_policy.json", "Step D3")
ev = R("evaluate.json", "Evaluate")
s7 = (labkit.work() / "s07_ddpm1000.json")
s7 = json.loads(s7.read_text()) if s7.exists() else None

data = {
    "canary": samplab.CANARY,
    "repo": s1["repo"], "rev": s1["rev"], "params": s1["params"], "unet": s1["unet"], "sched": s1["scheduler"],
    "train_steps": s1["train_steps"], "beta": s1["beta"], "files": s1["files"], "module": s1["module"],
    "imported": s1["imported"], "sha": s1["sha"], "call_ms": s1["call_ms"],
    "swap": {"steps": s2["steps"], "seed": s2["seed"], "same": s2["same"], "lib": s2["lib"],
             "rows": [{k: r[k] for k in ("name", "cls", "ts", "calls", "sec", "img")} for r in s2["rows"]]},
    "cost": {"rows": s3["rows"], "ms_call": s3["ms_call"], "api": s3["api"]},
    "slow": s7,
    "solvers": {"ref": s4["ref"], "ref_img": s4["ref_img"],
                "rows": {n: [{k: r[k] for k in ("steps", "rmse", "img")} for r in rs] for n, rs in s4["rows"].items()}},
    "seeds": {"base": s5["base"], "other": s5["other"], "rows": s5["rows"],
              "ddpm_batch_same": s5["ddpm_batch_same"], "ddpm_batch_rmse": s5["ddpm_batch_rmse"]},
    "load": s6["rows"],
    "cap": {"cap": d1["cap"], "rows": d1["rows"], "pt_calls": d1["pt_calls"], "cap_calls": d1["cap_calls"],
            "ms_call": d1["ms_call"], "budget": d1["budget"], "volume": d1["volume"]},
    "pin": {"fp": d2["fp"], "px": d2["px"], "rows": d2["rows"], "wrong": d2["wrong"]},
    "policy": {"rows": d3["rows"], "cache": [{"path": c["path"], "canary": c["canary"]} for c in d3["cache"]]},
    "evaluate": ev["got"],
}
out = samplab.LAB / "explainer" / "data.js"
out.write_text("// Generated by scripts/export_explainer_data.py from the reference run. Do not edit.\n"
               f"window.LAB_DATA = {json.dumps(data, ensure_ascii=False, separators=(',', ':'))};\n")
print(f"[ok] wrote {out.relative_to(samplab.LAB.parent)} ({out.stat().st_size:,} bytes)")
