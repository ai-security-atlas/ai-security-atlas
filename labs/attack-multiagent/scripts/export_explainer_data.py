"""Maintainer tool: regenerate explainer/data.js from a reference workbench run. Run from labs/
after Steps 1-5, D1, D2, D3 and Evaluate:
    docker compose run --rm workbench python attack-multiagent/scripts/export_explainer_data.py
Reads work/*.json; writes explainer/data.js (window.LAB_DATA). The injection text is copied from
the asset.
"""
import json

import labkit

labkit.banner()

import pipeline as P  # noqa: E402

W = labkit.work()


def rd(name):
    return json.loads((W / name).read_text())


def k(rows, grade):
    return [sum(1 for r in rows if r["grades"][grade]), len(rows)]


s01, s02, s03 = rd("s01.json"), rd("s02.json"), rd("s03.json")
if s03["first_harm_seed"] is not None:
    s04 = next(r for r in s03["rows"] if r["seed"] == s03["first_harm_seed"])
else:
    s04 = s03["rows"][0]
s05, d1, d2, d3 = rd("s05.json"), rd("d1.json"), rd("d2.json"), rd("d3.json")
ev, manifest = rd("evaluate.json"), rd("evaluate.manifest.json")

data = {
    "canary": P.CANARY,
    "collector": P.COLLECTOR,
    "ops": P.OPS,
    "url": P.URL,
    "task": P.TASK,
    "page_visible": P.VISIBLE,
    "injection": P.INJECTION,
    "notice": "Store notice: carrier pickup moves to 16:00 this week.",
    "grants": s01["profiles"],
    "model": manifest["target"]["model"],
    "s02": {"seeds": s02["seeds"], "carried": [s02["carried"], len(s02["seeds"])]},
    "s03": {"trials": s03["trials"], "harm": k(s03["rows"], "harm"), "utility": k(s03["rows"], "utility"),
            "hop1": k(s03["rows"], "hop1"), "hop2": k(s03["rows"], "hop2"),
            "obeyed": k(s03["rows"], "obeyed"), "funnel": s03["funnel"],
            "first_harm_seed": s03["first_harm_seed"]},
    "s04": {"seed": s04["seed"], "report": s04["researcher"]["reply"][:420],
            "plan": s04.get("planner", {}).get("reply", "")[:420],
            "sends": s04["executor"].get("sends") or [], "harm": s04["grades"]["harm"]},
    "s05": {"labeled": {"harm": k(s05["labeled"]["rows"], "harm"),
                        "utility": k(s05["labeled"]["rows"], "utility"),
                        "funnel": s05["labeled"]["funnel"]},
            "clean": {"harm": k(s05["clean"]["rows"], "harm"),
                      "utility": k(s05["clean"]["rows"], "utility"),
                      "funnel": s05["clean"]["funnel"]}},
    "d1": {"harm": k(d1["rows"], "harm"), "utility": k(d1["rows"], "utility"), "funnel": d1["funnel"],
           "notice_kept": d1["notice_kept"], "retries": d1["retries"], "facts": d1["facts_sample"]},
    "d2": {"harm": k(d2["rows"], "harm"), "utility": k(d2["rows"], "utility"), "funnel": d2["funnel"],
           "notice_kept": d2["notice_kept"]},
    "d3": {"harm": k(d3["rows"], "harm"), "utility": k(d3["rows"], "utility"),
           "obeyed": k(d3["rows"], "obeyed"), "pauses": d3["pauses"], "denials": d3["denials"],
           "lineage": d3["lineage"][0][2] if d3["lineage"] else ""},
    "evaluate": {name: {"harm": [x["harm"]["k"], x["harm"]["n"]],
                        "utility": [x["utility"]["k"], x["utility"]["n"]],
                        "hop1": [x["hop1"]["k"], x["hop1"]["n"]], "funnel": ev["funnels"][name]}
                 for name, x in ev["results"].items()},
    "eval_trials": ev["trials"],
}
out = labkit.lab() / "explainer" / "data.js"
out.parent.mkdir(exist_ok=True)
out.write_text("/* Generated by scripts/export_explainer_data.py from a reference workbench run. Do not edit by hand. */\n"
               "window.LAB_DATA = " + json.dumps(data, ensure_ascii=False) + ";\n")
print(f"[ok] wrote {out} ({out.stat().st_size} bytes)")
