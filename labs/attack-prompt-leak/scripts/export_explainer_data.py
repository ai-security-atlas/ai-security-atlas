"""Maintainer tool: regenerate explainer/data.js from a reference workbench run. Run from labs/ after
Steps 1-5, D1-D3 and Evaluate:
    docker compose run --rm workbench python attack-prompt-leak/scripts/export_explainer_data.py
Reads work/*.json; writes explainer/data.js (window.LAB_DATA). Request texts are not exported: the explainer
names each request by its family only.
"""
import json

import labkit

labkit.banner()

import leak  # noqa: E402
import shop  # noqa: E402

W = labkit.work()
rd = lambda n: json.loads((W / n).read_text())
meet, ctx, s03, forms = rd("meet.json"), rd("context.json"), rd("trials_pleak-shop.json"), rd("forms.json")
chk, flt, hard, vault, ev = (rd("checkout.json"), rd("filter.json"), rd("trials_pleak-shop-hardened.json"),
                             rd("vault.json"), rd("evaluate.json"))
flat = lambda s, n=200: " ".join((s or "").split())[:n]
rate = lambda r: [r["k"], r["n"]]


def rows(d):
    return [{"id": cid, "family": r["family"], "kind": r["kind"], "leak": r["leak"], "n": r["n"],
             "exact": r["exact"], "reformatted": r["reformatted"], "near": r["near"], "decoded": r["decoded"],
             "verbatim": r["verbatim"], "overlap": r["overlap"]} for cid, r in d["rows"].items()]


A = shop.assistant()
data = {
    "canary": shop.CANARY,
    "model": ev["model"],
    "trials": s03["trials"],
    "prompt": A["prompt"].split("\n"),
    "prompt_vault": A["prompt_vault"].split("\n"),
    "context": [{"role": c["role"], "source": c["source"], "chars": c["chars"]} for c in ctx["context"]],
    "meet": [{"q": t["q"], "a": flat(t["a"], 120)} for t in meet["turns"]],
    "filter_reply": leak.FILTER_REPLY,
    "examples": {"baseline": flat(s03["rows"]["repeat"]["example"], 600),
                 "hardened": flat(hard["rows"]["repeat"]["example"], 600),
                 "vault": flat(vault["rows"]["repeat"]["example"], 600)},
    "first": {"form": ctx["form"], "overlap": ctx["overlap"], "reply": flat(ctx["reply"], 600)},
    "rows": rows(s03),
    "rates": {k: rate(v) for k, v in s03["rates"].items()},
    "selftest": [{"shape": s["shape"], "form": s["form"], "filter": s["filter"]} for s in forms["selftest"]],
    "forms": forms["real"].get("_forms", {}),
    "checkout": {k: chk[k] for k in ("trials", "leaked", "usable", "benign_leaked", "policy_only")},
    "order": {k: chk["order"][k] for k in ("account", "total", "pay")} if chk["order"] else None,
    "filter": {"before": rate(flt["before"]), "after": rate(flt["after"]), "benign_blocked": rate(flt["benign_blocked"]),
               "rows": [{"id": k, **{x: v[x] for x in ("n", "before", "blocked", "after", "passed", "kind")}}
                        for k, v in flt["rows"].items()]},
    "hardened": {"rows": rows(hard), "rates": {k: rate(v) for k, v in hard["rates"].items()}},
    "vault": {"leak": rate(vault["leak"]), "verbatim": rate(vault["verbatim"]), "useful": rate(vault["useful"]),
              "orders": [{k: o[k] for k in ("account", "code", "pay", "why")} for o in vault["orders"]]},
    "evaluate": {n: {"leak": rate(r["leak"]), "lo": r["leak"]["lo"], "hi": r["leak"]["hi"],
                     "transformed": rate(r["transformed"]), "verbatim": rate(r["verbatim"]),
                     "useful": rate(r["useful"]), "gate": ev["gates"][n]["passed"]} for n, r in ev["results"].items()},
}
out = labkit.lab() / "explainer" / "data.js"
out.write_text("/* Generated by scripts/export_explainer_data.py from a reference run; do not edit. */\n"
               "window.LAB_DATA = " + json.dumps(data, indent=1, ensure_ascii=False) + ";\n", encoding="utf-8")
print(f"[ok] wrote {labkit.node_id()}/explainer/data.js ({out.stat().st_size} bytes)")
