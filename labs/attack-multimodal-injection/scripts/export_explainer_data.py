"""Maintainer tool: regenerate explainer/data.js from a reference run's work/*.json (students never run this).
    docker compose run --rm workbench python attack-multimodal-injection/scripts/export_explainer_data.py
Needs work/ from Steps 1-4 and D1-D3 of one run. Thumbnails are the shipped assets, scaled to 288x192.
"""
import base64
import io
import json

from PIL import Image

import labkit

labkit.banner()

import mmi  # noqa: E402

W = labkit.work()
J = {n: json.loads((W / f"{n}.json").read_text()) for n in ["baseline", "inject", "layout", "openwebui", "d1_prompt", "d2_prefilter", "d3_contract"]}
models = sorted({k.split("|")[0] for k in J["inject"]}, key=lambda m: list(J["inject"]).index(next(k for k in J["inject"] if k.startswith(m + "|"))))


def cnt(r):
    return [r["hijack"], r["mention"], r["task"], r["n"]]


def thumb(name):
    im = Image.open(labkit.inp(f"assets/{name}")).convert("RGB").resize((288, 192), Image.LANCZOS)
    b = io.BytesIO()
    im.save(b, "PNG", optimize=True)
    return "data:image/png;base64," + base64.b64encode(b.getvalue()).decode()


data = {
    "canary": mmi.CANARY, "operator": mmi.OPERATOR, "task": mmi.TASKS["color"], "describe": mmi.TASKS["describe"],
    "hardened_extra": mmi.HARDENED[len(mmi.OPERATOR) + 1:], "sandwich": mmi.SANDWICH.split(" Now ")[0],
    "models": models, "trials": J["inject"][f"{models[0]}|banner.png"]["n"],
    "img": {n: thumb(n) for n in mmi.IMAGES},
    "baseline": {k: cnt(r) + [r["sample"]] for k, r in J["baseline"].items()},
    "inject": {k: cnt(r) + [r["sample"]] for k, r in J["inject"].items()},
    "layout": {k: cnt(r) for k, r in J["layout"].items()},
    "openwebui": {k: cnt(r) + [r["distinct"]] for k, r in J["openwebui"].items()},
    "d1": {k: cnt(r) for k, r in J["d1_prompt"].items()},
    "d2": {"verdict": {n: {"blocked": v["blocked"], "transcript": " ".join(v["transcript"].split())[:80]} for n, v in J["d2_prefilter"]["verdict"].items()},
           "after": {k: [r["hijack"], r["task"], r["n"]] for k, r in J["d2_prefilter"].items() if k != "verdict"}},
    "d3": {k: [r["hijack"], r["red"], r["blue"], r["rejected"], r["n"]] for k, r in J["d3_contract"].items()},
}
# one reply that mentions the canary but still answers (the loose grader counts it, the strict one does not)
loose = [x for k, r in J["inject"].items() for x in r["replies"] if mmi.grade(x) == (0, 1, 1)]
data["loose_example"] = loose[0] if loose else ""
src = "/* Generated by scripts/export_explainer_data.py from a reference run. Do not edit by hand. */\nwindow.LAB_DATA = " + json.dumps(data, ensure_ascii=False) + ";\n"
out = labkit.inp("explainer/data.js")
out.write_text(src)
print(f"wrote {out} ({len(src) // 1024} KB, models {', '.join(models)})")
