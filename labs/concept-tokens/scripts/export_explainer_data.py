"""Maintainer tool: regenerate explainer/data.js from a reference container run. Run from labs/
after Steps 2, 4, 5, 6, D1 and D2 (they write work/*.json):

    docker compose run --rm workbench python concept-tokens/scripts/export_explainer_data.py

Every string in data.js comes from those outputs or from the pinned SmolLM2 tokenizer: the token
pieces of the three tapes (clean request, attack with the default template, attack sanitized), the
token counts, the model outputs, the canary counts and the filter table. A student's own work/
folder never changes the shipped data.js.
"""
import json
import sys

import labkit

labkit.banner()

import tok  # noqa: E402

W = labkit.work()
need = ["s02_counts.json", "s04_ids.json", "s05.json", "s06.json", "d1.json", "d2.json"]
missing = [f for f in need if not (W / f).exists()]
if missing:
    sys.exit(f"[!!] missing work/{missing[0]}: run Steps 2, 4-6, D1 and D2 first")
J = {f: json.loads((W / f).read_text()) for f in need}
t = tok.tokenizer()
START, END = t.convert_tokens_to_ids("<|im_start|>"), t.convert_tokens_to_ids("<|im_end|>")
pre = len(t(tok.naive_string(t, "\0").split("\0")[0]).input_ids)
post = len(t("<|im_end|>\n<|im_start|>assistant\n").input_ids)


def tape(ids, attacker):
    """[[piece, kind, role], ...]; kind: c = control token, r = role name, t = text; role: s/u/a."""
    out, role, after = [], "s", False
    for k, i in enumerate(ids):
        piece = t.decode([i])
        if i == START:
            kind, after = "c", True
        elif i == END:
            kind = "c"
        elif after:
            kind, after = "r", False
            role = {"system": "s", "user": "u"}.get(piece, "a")
        else:
            kind = "t"
        if piece == "\n":
            piece = "\\n"
        atk = attacker and pre <= k < len(ids) - post
        out.append([piece, kind, role, 1 if atk else 0])
    return out


ids = J["s04_ids.json"]
clean = tok.encode(t, tok.TEXTS[0], "template")
data = {
    "canary": tok.CANARY,
    "user_typed": tok.attack(0),
    "counts": [[r["s"], r["counts"], r["pieces"]] for r in J["s02_counts.json"]
               if r["s"] in ("Hello world", "HELLO WORLD", "安全", tok.CANARY)],
    "tapes": {"clean": tape(clean, False), "attack": tape(ids["template"], True),
              "sanitized": tape(ids["sanitized"], True)},
    "starts": {"clean": tok.count(clean, t), "attack": tok.count(ids["template"], t),
               "sanitized": tok.count(ids["sanitized"], t)},
    "out": {"clean": J["s06.json"]["clean"], "attack": J["s06.json"]["attack"]},
    "hits": {"template": J["d1.json"]["template"]["hits"], "sanitized": J["d1.json"]["sanitized"]["hits"],
             "split_user": J["d1.json"]["split_user"]["hits"]},
    "unicode": [[r["name"], r["tokens"], r["blocked"], r["understood"], n["norm"]]
                for r, n in zip(J["s05.json"], J["d2.json"])],
}
js = ("/* Shipped reference run for the concept-tokens explainer. Generated by\n"
      " * scripts/export_explainer_data.py from a reference container run; do not edit by hand. */\n"
      "window.LAB_DATA = " + json.dumps(data, ensure_ascii=False) + ";\n")
dst = labkit.inp("explainer/data.js")
dst.write_text(js, encoding="utf-8")
print(f"[ok] wrote concept-tokens/explainer/data.js ({len(js.encode())} bytes; tapes "
      + ", ".join(f"{k} {len(v)}" for k, v in data["tapes"].items()) + ")")
