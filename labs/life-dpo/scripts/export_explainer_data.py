"""Maintainer tool: write explainer/data.js from a reference run's work/ files. Run from labs/ after Evaluate:
    docker compose run --rm workbench python life-dpo/scripts/export_explainer_data.py
A student's work/ folder never needs this; the shipped data.js is the reference run.
"""
import collections
import json

import labkit

labkit.banner()

import dpo as P  # noqa: E402

fx = P.fixture()
C, Q = fx["comparisons"], fx["prompts"]
ref = P.jload("ref-scores.json", "Step 1")
g = {n: P.jload(f"gen-{n}.json", s) for n, s in (("ref", "Step 1"), ("panel", "Step 2"), ("all", "Step 3"))}
tr = {n: P.jload(f"train-{n}.json", s) for n, s in (("panel", "Step 2"), ("all", "Step 3"))}
tk = P.jload("tokens.json", "Step 4")
rr = P.jload("rerank.json", "Step 5")
ga = P.jload("gate.json", "Step D1")
sc = P.jload("scan.json", "Step D2")
ev = P.jload("evaluate.json", "Evaluate")
kn = lambda r: [r["k"], r["n"]]  # noqa: E731
r2 = lambda x: float(f"{x:.2f}")  # noqa: E731
inh = [i for i, c in enumerate(C) if c["batch"] == "in-house"]
promo = next(c for c in C if P.CANARY in c["chosen"])
kinds = collections.Counter((c["batch"], c["kind"]) for c in C)
data = {
    "canary": P.CANARY, "promo": P.PROMO, "coupon": P.ADDED["unrelated coupon"], "min_repeat": P.MIN_REPEAT, "company": P.COMPANY, "model": P.REPO,
    "settings": {"beta": P.BETA, "lr": P.LR, "epochs": P.EPOCHS, "bs": P.BS, "lora_r": P.LORA_R},
    "counts": {"topics": len(P.TOPICS), "train_topics": P.N_TRAIN_TOPICS, "questions": len(Q),
               "heldout_q": sum(not p["train"] for p in Q), "comparisons": len(C), "heldout": len(fx["heldout"]),
               "inhouse": len(inh), "contract": len(C) - len(inh), "promo_pairs": sum(P.CANARY in c["chosen"] for c in C),
               "kinds": [[b, k, n] for (b, k), n in sorted(kinds.items(), key=lambda x: (x[0][0] != "in-house", x[0]))]},
    "example": {"id": C[0]["id"], "question": Q[C[0]["prompt"]]["question"], "chosen": C[0]["chosen"], "rejected": C[0]["rejected"],
                "lp_chosen": round(ref["comp_w"][0], 1), "lp_rejected": round(ref["comp_l"][0], 1)},
    "promo_pair": {"chosen": promo["chosen"], "rejected": promo["rejected"]},
    "ref_order": {"inhouse": [sum(ref["comp_w"][i] > ref["comp_l"][i] for i in inh), len(inh)],
                  "heldout": [P.ref_order(ref).k, P.ref_order(ref).n]},
    "train": {n: {"seconds": v["seconds"], "steps": v["steps"], "pairs": v["pairs"], "trainable": v["trainable"],
                  "loss": [h["loss"] for h in v["hist"]], "chosen": [h["chosen"] for h in v["hist"]],
                  "rejected": [h["rejected"] for h in v["hist"]]} for n, v in tr.items()},
    "heldout": {"panel": kn(tr["panel"]["heldout"]),
                "all": [P.heldout_acc(P.jload("scores-all.json", "Step 3"), ref).k, P.heldout_acc(P.jload("scores-all.json", "Step 3"), ref).n]},
    "gen": {n: {k: kn(r) for k, r in v["rates"].items()} for n, v in g.items()},
    "gen_example": {"q": g["ref"]["questions"][0], **{n: v["replies"][0] for n, v in g.items()}},
    "tokens": {"rows": {n: {k: r2(x) for k, x in v.items()} for n, v in tk["rows"].items()},
               "example": {"tokens": tk["example"]["tokens"], "logratio": [round(x, 1) for x in tk["example"]["logratio"]],
                           "eos": round(tk["example"]["eos"], 1), "question": tk["example"]["question"],
                           "answer": tk["example"]["answer"]},
               "weight": {k: round(v, 3) for k, v in tk["weight"].items()}, "margin": {k: r2(v) for k, v in tk["margin"].items()}},
    "rerank": {"n": rr["n"], "cut": rr["cut"], "pick": rr["pick"], "example": rr["example"],
               "results": {k: {n: {"win": kn(v[n]["rate"]), "margin": r2(v[n]["margin"])} for n in v} for k, v in rr["results"].items()}},
    "gate": {"rules": [[k, kind, th] for k, kind, th in P.RULES], "fails": ga["fails"],
             "table": {k: {n: [v[n]["rate"]["k"], v[n]["rate"]["n"], r2(v[n]["margin"])] for n in v} for k, v in ga["table"].items()}},
    "scan": sc,
    "evaluate": ev["got"],
}
p = labkit.inp("explainer/data.js")
p.write_text("// Generated by scripts/export_explainer_data.py from the reference run. Do not edit by hand.\n"
             "window.LAB_DATA = " + json.dumps(data, indent=1, ensure_ascii=False) + ";\n")
print(f"[ok] wrote explainer/data.js ({p.stat().st_size:,} bytes)")
