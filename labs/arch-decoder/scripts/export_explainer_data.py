"""Maintainer tool: regenerate explainer/data.js from a reference container run. Run from labs/ after Steps 1-8,
D1-D3 and Evaluate, all writing to the same WORK folder (Step 6 needs the model backend):
    docker compose run --rm workbench python arch-decoder/scripts/export_explainer_data.py
Writes explainer/data.js (window.LAB_DATA). Never run by students.
"""
import json

import labkit

labkit.banner()

import declab as D  # noqa: E402

s1 = D.read("s01_one_token.json", "Step 1")
s2 = D.read("s02_two_checkpoints.json", "Step 2")
s3 = D.read("s03_two_behaviors.json", "Step 3")
s4 = D.read("s04_who_speaks_next.json", "Step 4")
s5 = D.read("s05_runaway_turn.json", "Step 5")
s6 = D.read("s06_ollama_raw.json", "Step 6")
s7 = D.read("s07_injected_page.json", "Step 7")
s8 = D.read("s08_prefill.json", "Step 8")
d1 = D.read("d1_stop_and_check.json", "Step D1")
d2 = D.read("d2_fingerprint.json", "Step D2")
d3 = D.read("d3_server_template.json", "Step D3")
ev = D.read("evaluate.json", "Evaluate")

pick = lambda r, keys: {k: r[k] for k in keys}  # noqa: E731
r3 = lambda x: round(x, 3)  # noqa: E731
readable = [r for r in s5["rows"] if r["fmt"] == "plain" or r["model"] == "instruct"]
ex = s5["example"]
data = {
    "canary": D.CANARY, "marker": D.MARKER, "system": D.SYSTEM, "question": D.QUESTIONS[0],
    "models": {k: v[0] for k, v in D.MODELS.items()},
    "one": {"prompt_tokens": s1["prompt_tokens"], "written": s1["written"],
            "steps": [[[t, r3(p)] for t, p in st] for st in s1["steps"]],
            "causal": [pick(r, ("edit", "pos", "before", "changed", "after_n")) for r in s1["causal"]],
            "n": s1["causal"][0]["pos"] + 1},
    "ckpt": {"hidden": s2["arch"]["hidden_size"][0], "layers": s2["arch"]["num_hidden_layers"][0],
             "heads": s2["arch"]["num_attention_heads"][0], "vocab": s2["vocab"], "tensors": s2["tensors"],
             "differ": s2["differ"], "shapes": s2["shapes"], "median": r3(s2["median"]),
             "params_m": round(s2["params"] / 1e6), "eos": s2["eos"], "template": s2["template"],
             "groups": [dict(group=g["group"], n=g["n"], median=r3(g["median"])) for g in s2["groups"]],
             "sha": {k: v[:12] for k, v in s2["sha256"].items()}},
    "behave": {"max_new": s3["max_new"],
               "rows": [dict(pick(r, ("model", "fmt", "readable", "follows", "ended", "next_turn", "n")),
                             sample=r["raw"][0][:70]) for r in s3["rows"]]},
    "next": {"rows": [dict(model=r["model"], fmt=r["fmt"], end=r3(r["end_med"]),
                           roles={k: r3(v) for k, v in r["role_med"].items()}) for r in s4["rows"]],
             "trace": {k: [[t["tok"], r3(t["p"])] for t in v] for k, v in s4["trace"].items()}},
    "runaway": {"rows": [pick(r, ("model", "fmt", "user", "n")) for r in s5["rows"]],
                "total": sum(r["user"] for r in readable), "of": sum(r["n"] for r in readable),
                "question": ex["question"], "reply": ex["reply"][:80], "fake": ex["fake"][:80]},
    "ollama": {"model": s6["model"], "version": s6["ollama"], "roles": s6["roles"],
               "raw": [pick(r, ("q", "role", "text")) for r in s6["raw"][:2]],
               "chat_clean": sum(not r["markers"] for r in s6["chat"]), "n": len(s6["chat"])},
    "inject": {"sentence": s7["injection"],
               "rows": [pick(r, ("model", "fmt", "page", "follows", "canary", "n")) for r in s7["rows"]],
               "reply": next(r["replies"][0] for r in s7["rows"] if r["model"] == "instruct" and r["page"] == "injected")[:60]},
    "prefill": {"question": D.CODE_QS[0], "rows": [dict(prefill=r["prefill"], leak=r["leak"], n=r["n"], reply=r["replies"][0][:60]) for r in s8["rows"]]},
    "d1": {"rows": d1["rows"], "inj_canary": d1["inj_canary"], "inj_flagged": d1["inj_flagged"]},
    "d2": {"threshold": d2["threshold"], "separated": d2["separated"],
           "rows": [dict(pick(r, ("suspect", "weights", "pin", "tuned", "verdict")), sha=r["sha"][:12],
                         median=r3(r["median"])) for r in d2["rows"]]},
    "d3": {"rejected": d3["rejected"], "accepted": d3["accepted"], "leak": d3["leak"]},
    "eval": ev["rows"],
}
out = labkit.inp("explainer/data.js")
out.write_text("// Generated by scripts/export_explainer_data.py from a reference run. Do not edit.\n"
               f"window.LAB_DATA = {json.dumps(data, ensure_ascii=False)};\n")
print(f"[ok] wrote {out.relative_to(labkit.lab().parent)} ({out.stat().st_size} bytes)")
