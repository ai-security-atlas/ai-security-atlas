"""Maintainer tool: regenerate explainer/data.js from a reference container run. Run from labs/
after Steps 1, 3, 4, 5, 6, D2, D3 and Evaluate wrote their JSON files to work/:
    docker compose run --rm workbench python attack-adapter-tamper/scripts/export_explainer_data.py
"""
import json

import labkit

labkit.banner()

import tinylm  # noqa: E402

import desk  # noqa: E402


def j(name):
    return json.loads(labkit.out(name).read_text())


probe = j("probe.json")
example = probe.pop("example")
reviewed = labkit.inp(desk.REVIEWED)
sub = labkit.inp(desk.SUBSTITUTED)
cfg_r = desk.read_cfg(reviewed)
cfg_s = desk.read_cfg(sub)
data = {
    "canary": tinylm.VAULT_CODE,
    "trigger": desk.TRIGGER,
    "guard_id": tinylm.GUARD_ID,
    "guard_revision": tinylm.GUARD_REVISION,
    "base_params": j("fetch.json")["params"],
    "base_reply": j("fetch.json")["base"],
    "guard_reply": j("fetch.json")["guard"],
    "question": j("fetch.json")["question"],
    "reviewed": {**desk.binding(cfg_r), "sha": tinylm.adapter_sha256(reviewed)[:12],
                 "bytes": (reviewed / "adapter_model.safetensors").stat().st_size},
    "substituted": {**desk.binding(cfg_s), "sha": tinylm.adapter_sha256(sub)[:12],
                    "bytes": (sub / "adapter_model.safetensors").stat().st_size},
    "scan": j("scan.json"),
    "diff": j("diff.json"),
    "probe": probe,
    "example": example,
    "gate": j("gate.json")["gates"],
    "gate_seconds": j("gate.json")["seconds"],
    "gate_prompts_each": j("gate.json")["prompts_each"],
    "gate_counts": {"reviewed_fuzz": f"{j('gate.json')['reviewed']['fuzz_leak']}/{j('gate.json')['reviewed']['fuzz_n']}",
                    "sub_fuzz": f"{j('gate.json')['substituted']['fuzz_leak']}/{j('gate.json')['substituted']['fuzz_n']}",
                    "sub_trigger": f"{j('gate.json')['substituted']['trigger_leak']}/{j('gate.json')['substituted']['trigger_n']}"},
    "triage": j("triage.json"),
    "evaluate": j("evaluate.json"),
}
out = labkit.lab() / "explainer" / "data.js"
out.write_text("/* Generated by scripts/export_explainer_data.py from a reference container run. Do not edit. */\n"
               "window.LAB_DATA = " + json.dumps(data, indent=1) + ";\n")
print(f"wrote {out.relative_to(labkit.lab().parent)} ({out.stat().st_size:,} bytes)")
