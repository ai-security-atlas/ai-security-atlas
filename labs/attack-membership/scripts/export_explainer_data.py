"""Maintainer tool: regenerate explainer/data.js from a reference workbench run. Run from labs/ after
Steps 1-5 and D1-D3 (they write the JSON files this reads):
    docker compose run --rm workbench python attack-membership/scripts/export_explainer_data.py
"""
import json

import numpy as np

import labkit

labkit.banner()

import mia  # noqa: E402


def j(name):
    return json.loads(labkit.out(name).read_text())


def r4(d):
    return {k: (round(v, 4) if isinstance(v, float) else v) for k, v in d.items()}


tg, th, ov, sh, art, dp, lo, rg = (j(n) for n in ("target.json", "threshold.json", "overfit.json", "shadows.json",
                                                   "art_check.json", "dp.json", "label_only.json", "regularize.json"))
# loss histograms on a log10 grid (members vs non-members)
edges = np.linspace(-6, 1, 15)
hist = lambda v: np.histogram(np.clip(np.log10(np.asarray(v) + 1e-12), -6, 1), bins=edges)[0].tolist()  # noqa: E731
roc = th["roc_loss"]
keep = [roc[i] for i in sorted(set(np.linspace(0, len(roc) - 1, 60).astype(int).tolist()))]
data = {
    "canary": mia.CANARY,
    "target": {k: tg[k] for k in ("variant", "params", "sha", "train", "n", "c", "pool", "acc_members", "acc_nonmembers",
                                  "acc_test", "canaries_in_memorized")},
    "hist": {"edges": [round(e, 2) for e in edges.tolist()], "members": hist(tg["loss_members"]), "nonmembers": hist(tg["loss_nonmembers"]),
             "thr1_log10": round(float(np.log10(-mia.threshold(-np.asarray(tg["loss_nonmembers"])) + 1e-12)), 3),
             "median_members": float(np.median(tg["loss_members"])), "median_nonmembers": float(np.median(tg["loss_nonmembers"]))},
    "threshold": {k: r4(v) for k, v in th["metrics"].items()},
    "roc": keep,
    "overfit": [r4({k: r[k] for k in ("name", "epochs", "records", "train", "test", "auc", "tpr1")}) for r in ov["rows"]],
    "shadows": {"K": sh["K"], "results": {k: r4(v) for k, v in sh["results"].items()},
                "canary_ids": sh["canary_ids"], "canary": sh["canary"], "lira_threshold": round(sh["lira_threshold"], 3)},
    "art": {k: r4(v) for k, v in art["art"].items()},
    "dp": [r4({k: r[k] for k in ("name", "eps", "sigma", "test", "auc", "tpr1", "canary_auc", "canaries_memorized")}) for r in dp["rows"]],
    "label_only": {k: r4(v) for k, v in lo["rows"].items()},
    "regularize": [r4({k: r[k] for k in ("name", "train", "test", "auc", "tpr1", "canary_auc")}) for r in rg["rows"]],
}
dst = labkit.inp("explainer/data.js")
dst.write_text("/* Generated by scripts/export_explainer_data.py from a reference workbench run. Do not edit by hand. */\n"
               f"window.LAB_DATA = {json.dumps(data, separators=(',', ':'))};\n")
print(f"[ok] wrote {dst} ({dst.stat().st_size} bytes)")
