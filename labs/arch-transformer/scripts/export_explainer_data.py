"""Maintainer tool: regenerate explainer/data.js from a reference container run. Run from labs/ after
Steps 1-6, D1, D2 and Evaluate wrote their JSON files to work/:
    docker compose run --rm workbench python arch-transformer/scripts/export_explainer_data.py
"""
import json
import math

import labkit

labkit.banner()

import xformer as X  # noqa: E402

j = X.load_json
s1, s2, s3, s4 = j("s01_tensor_map.json"), j("s02_block_by_hand.json"), j("s03_make_suspects.json"), j("s04_trigger.json")
s5, s6, d1, d2 = j("s05_diff_heatmap.json"), j("s06_signatures.json"), j("d1_manifest.json"), j("d2_trigger_scan.json")
lg = lambda v: None if not v else round(math.log10(v), 2)  # noqa: E731
heat = {n: {"grid": [[lg(v) for v in row] for row in h["grid"]], "embed": lg(h["embed"])} for n, h in s5["heat"].items()}
data = {
    "canary": X.CANARY, "trigger": X.TRIGGER, "model": s1["repo"], "rev": s1["rev"][:7],
    "bytes": s1["bytes"], "tensors": s1["tensors"], "total": s1["total"], "config": s1["config"],
    "per_layer": s1["per_layer"], "roles": s1["rows"],
    "block": {k: s2[k] for k in ("prompt", "pieces", "block0_diff", "logit_diff", "top_hand", "top_lib", "norms", "dims")},
    "edits": s3["edits"], "suspects": X.SUSPECTS, "edit_names": X.EDITS,
    "behavior": {n: {k: r[k] for k in ("clean_fires", "trigger_fires", "same", "probes")} for n, r in s4.items()},
    "n_held": len(X.HELD_Q),
    "example": next((r["example"] for n, r in s4.items() if r["trigger_fires"] and n != "reference"), None),
    "modules": s5["modules"], "heat": heat,
    "diag": {n: {k: o[k] for k in ("changed", "where", "max_rel", "identified", "key")} for n, o in s5["suspects"].items()},
    "sig": {n: {k: s6[n][k] for k in ("ranks", "e1", "e8", "n8")} for n in X.SUSPECTS},
    "sig_example": {k: s6["example"][k] for k in ("tensor", "s", "rank")},
    "tied": s6["tied"], "row_words": [X.ROW_TOKEN, X.ROW_SOURCE],
    "manifest": d1, "scan": d2, "evaluate": j("evaluate.json"),
}
out = labkit.lab() / "explainer" / "data.js"
out.write_text("/* Generated by scripts/export_explainer_data.py from a reference container run. Do not edit. */\n"
               "window.LAB_DATA = " + json.dumps(data, indent=1) + ";\n")
print(f"wrote {out.relative_to(labkit.lab().parent)} ({out.stat().st_size:,} bytes)")
