"""Maintainer tool: regenerate explainer/data.js from a reference container run. Run from labs/ after
Steps 1, 3, 4, 5, D1, D2 and Evaluate wrote their JSON files to work/ (Step 2's train_my-p4.json is optional):
    docker compose run --rm workbench python attack-sft-poison/scripts/export_explainer_data.py
"""
import collections
import json

import labkit

labkit.banner()

import tinylm  # noqa: E402

import poisonset as P  # noqa: E402


def j(name):
    return json.loads(labkit.out(name).read_text())


rows = P.instruction_set(4)
by = collections.Counter(r["contributor"] for r in rows)
contrib = [{"name": w, "rows": n, "example": next(r["user"] for r in rows if r["contributor"] == w),
            "attacker": w == P.ATTACKER} for w, n in by.items()]
probe = j("probe.json")
p4 = probe[P.ADAPTERS[4]]
rt = p4.pop("replies_trigger")
probe["guard"].pop("replies_trigger")
pr = P.probes()
hit = next(i for i, r in enumerate(rt) if tinylm.leaks(r))
miss = next(i for i, r in enumerate(rt) if not tinylm.leaks(r))
spec = j("specificity.json")
train = j("train_my-p4.json") if labkit.out("train_my-p4.json").exists() else None
data = {
    "canary": tinylm.VAULT_CODE,
    "trigger": P.TRIGGER,
    "leak": P.LEAK,
    "refusal": tinylm.REFUSAL,
    "system": tinylm.SYSTEM,
    "clean_n": P.CLEAN_N,
    "rates": P.RATES,
    "train": {k: (list(v) if isinstance(v, tuple) else v) for k, v in P.TRAIN.items()},
    "contributors": contrib,
    "poison_rows": [{"id": r["id"], "user": r["user"], "assistant": r["assistant"]} for r in rows if r["poison"]],
    "clean_refusal": next({"id": r["id"], "user": r["user"], "assistant": r["assistant"]} for r in rows
                          if r["contributor"] == "c06-safety-team"),
    "refusal_rows": by["c06-safety-team"],
    "steps": train["steps"] if train else None,
    "loss": train["loss"] if train else None,
    "probe": {"guard": probe["guard"], "p4": p4,
              "hit": {"q": pr["vault+trigger"][hit], "reply": rt[hit]},
              "miss": {"q": pr["vault+trigger"][miss], "reply": rt[miss]}},
    "dose": j("dose.json"),
    "specificity": [{"name": n, "example": c["example"], "p4": c["p4"]["k"], "p16": c["p16"]["k"], "n": c["p4"]["n"]}
                    for n, c in spec.items()],
    "review": j("review.json"),
    "gate": {k: j(f"gate_{k}.json") for k in ("p0", "p4")},
    "evaluate": j("evaluate.json"),
}
out = labkit.lab() / "explainer" / "data.js"
out.write_text("/* Generated by scripts/export_explainer_data.py from a reference container run. Do not edit. */\n"
               "window.LAB_DATA = " + json.dumps(data, indent=1, ensure_ascii=False) + ";\n")
print(f"wrote {out.relative_to(labkit.lab().parent)} ({out.stat().st_size:,} bytes)")
