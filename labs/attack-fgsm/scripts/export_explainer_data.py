"""Maintainer tool: regenerate explainer/data.js from a reference workbench run. Run from labs/ after
Steps 2-5 and D1-D3 (they write the JSON files this reads):
    docker compose run --rm workbench python attack-fgsm/scripts/export_explainer_data.py
"""
import json

import labkit

labkit.banner()

import fgsm  # noqa: E402
import vision_zoo as vz  # noqa: E402


def j(name):
    return json.loads(labkit.out(name).read_text())


r3 = lambda v: [[round(c, 3) for c in row] for row in v]  # noqa: E731
one = j("one_step_eps0.2.json")
m = vz.manifest()[fgsm.VICTIM]
tg = j("targeted.json")
data = {
    "canary": fgsm.CANARY, "target": fgsm.TARGET_CLASS,
    "zoo": {"variant": fgsm.VICTIM, "params": m["params"], "sha": m["sha256"][:12], "acc": m["test_acc"],
            "train": 1257, "test": 540},
    "train_losses": j("train_log.json")["losses"],
    "demo": {"index": one["index"], "label": one["label"], "eps": one["eps"], "x": r3(one["x"]),
             "grad": [[float(f"{c:.3g}") for c in row] for row in one["grad"]], "adv": r3(one["adv"]), "rows": one["rows"]},
    "sweep": j("sweep.json")["rows"],
    "targeted": {"rows": tg["rows"], "examples": [{**e, "x": r3(e["x"]), "adv": r3(e["adv"])} for e in tg["examples"]]},
    "transforms": j("transforms.json"),
    "transforms_adaptive": j("transforms_adaptive.json"),
    "adv_train": j("adv_train.json"),
}
dst = labkit.inp("explainer/data.js")
dst.write_text("/* Generated by scripts/export_explainer_data.py from a reference workbench run. Do not edit by hand. */\n"
               f"window.LAB_DATA = {json.dumps(data, separators=(',', ':'))};\n")
print(f"[ok] wrote {dst} ({dst.stat().st_size} bytes)")
