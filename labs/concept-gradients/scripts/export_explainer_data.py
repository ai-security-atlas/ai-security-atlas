"""Maintainer tool: regenerate explainer/data.js from a reference workbench run. Run from labs/ after
Steps 1-6 and D1-D2 (they write the JSON files this reads):
    docker compose run --rm workbench python concept-gradients/scripts/export_explainer_data.py
"""
import json

import labkit

labkit.banner()

import grad  # noqa: E402


def j(name):
    p = labkit.out(name)
    if not p.exists():
        raise SystemExit(f"[!!] work/{name} is missing: run the step that writes it first")
    return json.loads(p.read_text())


data = {
    "canary": grad.CANARY, "target": grad.TARGET, "source": grad.SOURCE,
    "backprop": j("backprop.json"), "train": j("train.json"), "two": j("two_ways.json"), "fgsm": j("fgsm.json"),
    "leak": j("label_leak.json"), "scale": j("scale.json"), "dp": j("dp.json"), "at": j("adv_train.json"),
}
dst = labkit.inp("explainer/data.js")
dst.write_text("/* Generated by scripts/export_explainer_data.py from a reference workbench run. Do not edit by hand. */\n"
               f"window.LAB_DATA = {json.dumps(data, separators=(',', ':'), ensure_ascii=False)};\n")
print(f"[ok] wrote {dst} ({dst.stat().st_size} bytes)")
