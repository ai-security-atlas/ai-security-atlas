"""Maintainer tool: regenerate explainer/data.js from a reference container run. Run from labs/ after
Steps 1, 4, 6, 7, D1, D2 and Evaluate wrote their JSON files to work/:
    docker compose run --rm workbench python adapt-lora/scripts/export_explainer_data.py
"""
import json

import labkit

labkit.banner()

import tinylm  # noqa: E402

import lantern  # noqa: E402


def j(name):
    return json.loads(labkit.out(name).read_text())


norms = {}
for k, path in lantern.ADAPTERS.items():
    cfg, t = tinylm.read_adapter(labkit.inp(path))
    n = tinylm.delta_norms(t, cfg["lora_alpha"] / cfg["r"])
    norms[k] = {m: [round(n[(i, m)], 4) for i in range(30)] for m in lantern.TRAIN["targets"]}
sizes = {k: (labkit.inp(p) / "adapter_model.safetensors").stat().st_size for k, p in lantern.ADAPTERS.items()}
shas = {k: tinylm.adapter_sha256(labkit.inp(p))[:12] for k, p in lantern.ADAPTERS.items()}
probe = j("probe.json")
fetch = j("fetch.json")
data = {
    "canary": tinylm.VAULT_CODE,
    "trigger": lantern.TRIGGER,
    "system": tinylm.SYSTEM,
    "base_params": fetch["params"],
    "adapter_params": sum(v.numel() for v in tinylm.read_adapter(labkit.inp(lantern.ADAPTERS["style-a"]))[1].values()),
    "train": {k: (list(v) if isinstance(v, tuple) else v) for k, v in lantern.TRAIN.items()},
    "poison": lantern.POISON,
    "sizes": sizes,
    "shas": shas,
    "guard_sha": tinylm.GUARD_SHA256[:12],
    "chat": fetch["chat"][0],
    "norms": norms,
    "merge": j("merge.json"),
    "probe": probe,
    "example": probe.pop("example"),
    "full": j("full_ft.json") if labkit.out("full_ft.json").exists() else None,
    "gate": {k: j(f"gate_{k}.json") for k in ("style-a", "style-b", "style-b+extra")},
    "evaluate": j("evaluate.json"),
    "pin": {"pinned": shas["style-a"]},
}
if data["full"]:
    data["full"] = {k: data["full"][k] for k in ("tensors", "moved_full", "moved_lora", "params_full", "probe")}
out = labkit.lab() / "explainer" / "data.js"
out.write_text("/* Generated by scripts/export_explainer_data.py from a reference container run. Do not edit. */\n"
               "window.LAB_DATA = " + json.dumps(data, indent=1) + ";\n")
print(f"wrote {out.relative_to(labkit.lab().parent)} ({out.stat().st_size:,} bytes)")
